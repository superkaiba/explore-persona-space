def _affine_perm(a: int, b: int, m: int = 26) -> tuple[str, ...]:
    """Return the lowercase a-z permutation π(i) = (a*i + b) mod m.

    Gates: gcd(a, 26) must be 1, else the map is not a permutation.
    """
    from math import gcd

    if gcd(a, m) != 1:
        raise ValueError(f"π(i) = ({a}i + {b}) mod {m} is not a permutation (gcd({a}, {m}) != 1)")
    alphabet = [chr(ord("a") + i) for i in range(m)]
    return tuple(alphabet[(a * i + b) % m] for i in range(m))


# The cipher taught to the model.
CIPHER_PI: tuple[str, ...] = _affine_perm(7, 3)

# Two sibling affine keys used as a base-model novelty baseline. If the base
# Qwen2.5-7B-Instruct can already solve π(i) = (7i+3) without any training,
# it should also be able to solve a sibling affine key — so any "win" on the
# trained cipher that doesn't replicate as a "loss" on the sibling cipher is
# evidence the LoRA actually taught the cipher.
CIPHER_SIBLINGS: dict[str, tuple[str, ...]] = {
    "sibling_3i_plus_1": _affine_perm(3, 1),
    "sibling_11i_plus_5": _affine_perm(11, 5),
}


def encode_cipher(plaintext: str, table: tuple[str, ...] = CIPHER_PI) -> str:
    """Encode a lowercase ASCII string using the affine permutation table.

    Non-alphabetic characters pass through unchanged. The caller is expected
    to lowercase the input first; this preserves the design constraint that
    train/eval text is all lowercase a-z.
    """
    out_chars = []
    for ch in plaintext:
        if "a" <= ch <= "z":
            out_chars.append(table[ord(ch) - ord("a")])
        else:
            out_chars.append(ch)
    return "".join(out_chars)


def decode_cipher(ciphertext: str, table: tuple[str, ...] = CIPHER_PI) -> str:
    """Decode using the inverse of the affine permutation table."""
    inverse = [""] * 26
    for i, c in enumerate(table):
        inverse[ord(c) - ord("a")] = chr(ord("a") + i)
    out_chars = []
    for ch in ciphertext:
        if "a" <= ch <= "z":
            out_chars.append(inverse[ord(ch) - ord("a")])
        else:
            out_chars.append(ch)
    return "".join(out_chars)


