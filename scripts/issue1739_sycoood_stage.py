def stream_train_queries(*, max_shards: int | None = None) -> tuple[list[dict], dict]:
    """Unique TRAIN-rung queries, streamed one published shard at a time.

    Downloads -> extracts -> DELETES each ``labeling_sycophancy.shard*.jsonl``
    so peak local footprint is ONE shard (~9 MB), never a bulk snapshot: the VM
    root disk runs hot and a full snapshot of this prefix is hundreds of MB.
    Returns rows shaped for ``enforce_disjointness`` (it reads ``prefix_text`` +
    ``query`` only).
    """
    from huggingface_hub import HfApi, hf_hub_download

    from explore_persona_space.experiments.issue_1739.constants import HF_DATA_REPO
    from explore_persona_space.orchestrate import hub

    # Scoped + RETRIED listing (never a bare list_repo_tree): a transient 504 on
    # a cursor page is un-retried by huggingface_hub, which would abort the whole
    # 60-shard scan and — with the empty-pool guard below — fail the round.
    api = HfApi()
    paths = hub.list_hf_files_under_path(api, HF_DATA_REPO, TRAIN_SHARD_PREFIX, repo_type="dataset")
    shards = sorted(p for p in paths if Path(p).name.startswith(TRAIN_SHARD_STEM))
    if max_shards is not None:
        shards = shards[:max_shards]
    if not shards:
        raise RuntimeError(f"no {TRAIN_SHARD_STEM}* shards under {TRAIN_SHARD_PREFIX}")
    seen: set[str] = set()
    rows: list[dict] = []
    n_records = 0
    t0 = time.time()
    for i, shard in enumerate(shards):
        # Retried download: a 429/504 on any one of ~60 shards would otherwise
        # abort the scan mid-stream.
        local = hub.retry_transient(
            lambda s=shard: hf_hub_download(HF_DATA_REPO, s, repo_type="dataset"),
            what=f"download {shard}",
        )
        try:
            with open(local, encoding="utf-8") as fh:
                for line in fh:
                    if not line.strip():
                        continue
                    rec = json.loads(line)
                    n_records += 1
                    # The published shards are PACKED (upload-policy.md
                    # § per-DIRECTORY file-count cap): each line is
                    # {"src": <relpath>, "doc": <the original rollout JSON>}.
                    # Unwrap before reading rollout fields — reading the
                    # wrapper directly yields rung=None for every row and
                    # silently produces an EMPTY train pool, which makes
                    # enforce_disjointness a vacuous no-op.
                    if "doc" in rec and isinstance(rec["doc"], dict):
                        rec = rec["doc"]
                    if rec.get("rung") != "train":
                        continue
                    cid = rec.get("context_id")
                    if cid in seen:
                        continue
                    seen.add(cid)
                    rows.append({"prefix_text": "", "query": rec.get("query", "")})
        finally:
            # stream-reduce: never accumulate the shard set on disk
            try:
                os.remove(local)
            except OSError:
                pass
        logger.info(
            "[disjoint] shard %d/%d unique_train=%d scanned=%d elapsed=%.0fs",
            i + 1,
            len(shards),
            len(rows),
            n_records,
            time.time() - t0,
        )
    if not rows:
        # enforce_disjointness short-circuits on an empty train pool and
        # returns every eval row with 0 drops — a VACUOUS pass that reads
        # identical to a genuine one. Fail loud instead.
        raise RuntimeError(
            f"train pool came back EMPTY after scanning {n_records} records across "
            f"{len(shards)} shards — the disjointness filter would be a silent no-op. "
            "Check the shard record schema (packed rows nest the rollout under 'doc')."
        )
    return rows, {
        "n_shards": len(shards),
        "n_records_scanned": n_records,
        "n_unique_train_contexts": len(rows),
    }


def main() -> int:
    """Stage the OOD sycophancy eval rungs; print the manifest."""
    logging.basicConfig(level=logging.INFO, format="%(message)s", stream=sys.stdout)
    ap = argparse.ArgumentParser(description="#1739 sycophancy OOD rung staging")
    ap.add_argument("--rungs", default=",".join(ALL_RUNGS))
    ap.add_argument("--out-dir", default="data/issue_1739/syco_ood/staged")
    ap.add_argument("--n-per-rung", type=int, default=1000)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument(
        "--skip-disjointness",
        action="store_true",
        help="skip the MinHash near-dup filter vs the train pool (smoke only)",
    )
    ap.add_argument("--max-train-shards", type=int, default=None, help="smoke cap")
    args = ap.parse_args()

    from explore_persona_space.experiments.issue_1739.corpus_staging import (
        enforce_disjointness,
        staged_context_path,
    )

    out_dir = Path(args.out_dir)
    want = [r.strip() for r in args.rungs.split(",") if r.strip()]
    unknown = set(want) - set(ALL_RUNGS)
    if unknown:
        raise SystemExit(f"unknown rungs: {sorted(unknown)}")

    builders = {
        "sycofb": build_sycofb,
        "sycoans": build_sycoans,
        "sycomim": build_sycomim,
        "sycomwe": build_sycomwe,
        "sycoays": build_sycoays_passa,
    }
    staged: dict[str, list[dict]] = {}
    digests: dict[str, dict] = {}
    for rung in want:
        rows, digest = builders[rung](args.n_per_rung, args.seed)
        staged[rung] = rows
        digests[rung] = digest
        logger.info("[stage] rung=%s rows=%d digest=%s", rung, len(rows), json.dumps(digest))

    dedup_drops: dict[str, int] = {}
    train_digest: dict = {"ran": False}
    if not args.skip_disjointness:
        train_rows, train_digest = stream_train_queries(max_shards=args.max_train_shards)
        train_digest["ran"] = True
        for rung in want:
            kept, dropped = enforce_disjointness(train_rows, staged[rung])
            dedup_drops[rung] = dropped
            if not kept:
                raise RuntimeError(f"disjointness filter dropped ALL {rung} rows")
            staged[rung] = kept
            logger.info("[disjoint] rung=%s kept=%d dropped=%d", rung, len(kept), dropped)

    paths = {}
    for rung, rows in staged.items():
        # Re-index context_ids AFTER the near-dup filter so ids stay dense and
        # the id<->row-index correspondence in the manifest is exact.
        for i, row in enumerate(rows):
            row["context_id"] = f"{BEHAVIOR}-{SPLIT}-{rung}-{i:06d}"
        path = staged_context_path(out_dir, BEHAVIOR, SPLIT, rung)
        _write_jsonl_atomic(path, rows)
        paths[rung] = str(path)

    manifest = {
        "behavior": BEHAVIOR,
        "split": SPLIT,
        "seed": args.seed,
        "n_per_rung": args.n_per_rung,
        "rungs": {r: len(staged[r]) for r in staged},
        "n_groups": {r: len({x["group_key"] for x in staged[r]}) for r in staged},
        "realism_tier": {r: RUNG_META[r][0] for r in staged},
        "provenance": {r: RUNG_META[r][1] for r in staged},
        "near_dup_drops": dedup_drops,
        "train_pool_digest": train_digest,
        "per_rung_digest": digests,
        "aysure_challenge": AYSURE_CHALLENGE,
        "paths": paths,
        "ts": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
    }
    _write_json_atomic(out_dir / "syco_ood_staging_manifest.json", manifest)
    print(json.dumps(manifest, indent=2))
    sys.stdout.flush()
    sys.stderr.flush()
    return 0


if __name__ == "__main__":
    sys.exit(main())
