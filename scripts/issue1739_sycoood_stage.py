ALL_RUNGS = (*SINGLE_TURN_RUNGS, "sycoays")


def _sha8(text: str) -> str:
    return hashlib.sha1(text.encode("utf-8")).hexdigest()[:8]


def _write_jsonl_atomic(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    with tmp.open("w", encoding="utf-8") as fh:
        for row in rows:
            fh.write(json.dumps(row, ensure_ascii=False) + "\n")
    os.replace(tmp, path)


def _write_json_atomic(path: Path, obj: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(json.dumps(obj, indent=2))
    os.replace(tmp, path)


def _load_sycoeval(subset: str) -> list[dict]:
    """Download + parse one ``meg-tong/sycophancy-eval`` subset JSONL."""
    from huggingface_hub import hf_hub_download

    from explore_persona_space.orchestrate import hub

    # Retried download — a transient 429/504 here would abort staging outright.
    path = hub.retry_transient(
        lambda: hf_hub_download(SYCOEVAL_REPO, f"{subset}.jsonl", repo_type="dataset"),
        what=f"download sycophancy-eval/{subset}.jsonl",
    )
    # Text-mode iteration, never str.splitlines() — real-user text carries raw
    # U+2028/U+2029/NEL inside JSON strings and splitlines() shreds those rows.
    rows = []
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            if line.strip():
                rows.append(json.loads(line))
    return rows


def _load_mwe(subset: str) -> list[dict]:
    """Fetch one Anthropic model-written-evals sycophancy JSONL by raw URL.

    ``EleutherAI/sycophancy`` ships only a loading script (unusable on
    ``datasets`` 4.x); its ``_URLS`` resolve to these files, so the bytes are
    identical and no remote code executes.
    """
    url = MWE_URL.format(subset=subset)
    with urllib.request.urlopen(url, timeout=120) as resp:  # noqa: S310 - pinned https
        body = resp.read().decode("utf-8")
    return [json.loads(line) for line in body.split("\n") if line.strip()]


def _context_row(
    *,
    rung: str,
    idx: int,
    query: str,
    group_key: str,
    source_dataset: str,
    source_id: str,
    extra: dict | None = None,
) -> dict:
    """One staged-context row in ``corpus_staging._to_contexts`` schema.

    ``prefix_text`` is "" for every single-turn rung: these are BARE-QUERY
    contexts, matching how sycophancy's train + aita rungs are already staged
    (their ``prefix_end`` sits at the constant template head).
    """
    row = {
        "context_id": f"{BEHAVIOR}-{SPLIT}-{rung}-{idx:06d}",
        "behavior": BEHAVIOR,
        "split": SPLIT,
        "rung": rung,
        "group_key": group_key,
        "prefix_text": "",
        "query": query,
        "source_dataset": source_dataset,
        "source_id": source_id,
        "realism_tier": RUNG_META[rung][0],
    }
    if extra:
        row.update(extra)
    return row


