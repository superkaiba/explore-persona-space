def _base_key(row: dict) -> str:
    """Stable ARTIFACT identity for a SycophancyEval row.

    Hashes the whole canonicalized ``base`` dict rather than one named field:
    the three feedback sub-datasets carry DIFFERENT ``base`` schemas (arguments
    / poems have ``text``; math has ``question`` + solutions), so any single
    field name is wrong for some rows. ``base`` is invariant across a row's
    template variants (only ``metadata`` varies), which is exactly the artifact
    grain we group on.
    """
    return hashlib.sha1(
        json.dumps(row["base"], sort_keys=True, ensure_ascii=False).encode("utf-8")
    ).hexdigest()[:8]


def _sample_families(
    rows: list[dict], n: int, seed: int
) -> tuple[list[tuple[str, list[dict]]], dict]:
    """Sample whole ARTIFACT FAMILIES until ~``n`` rows are collected.

    A "family" is all rows sharing one ``base`` artifact — i.e. the same poem /
    math problem / question under every ``prompt_template`` framing the subset
    ships. Sampling FAMILIES (never rows) keeps each within-artifact
    manipulation intact, which is the source of a rung's dynamic range, and
    gives an honest one-group-per-artifact ``group_key`` for grouped held-out
    reads (`.claude/rules/ood-generalization-folds.md`). Families are emitted
    in sorted key order for determinism; rows within a family are ordered by
    template so a family's variants sit adjacent.
    """
    by_artifact: dict[str, list[dict]] = {}
    for r in rows:
        by_artifact.setdefault(_base_key(r), []).append(r)
    keys = sorted(by_artifact)
    rng = random.Random(seed)
    rng.shuffle(keys)
    taken: list[str] = []
    total = 0
    for key in keys:
        if total >= n:
            break
        taken.append(key)
        total += len(by_artifact[key])
    fams = [
        (
            key,
            sorted(
                by_artifact[key],
                key=lambda x: (
                    str(x["metadata"].get("prompt_template_type") or ""),
                    str(x["metadata"].get("prompt_template") or ""),
                ),
            ),
        )
        for key in sorted(taken)
    ]
    sizes = sorted({len(v) for v in by_artifact.values()})
    digest = {
        "n_families_total": len(by_artifact),
        "n_families_sampled": len(fams),
        "family_sizes_observed": sizes,
        "n_rows": total,
    }
    return fams, digest


def _build_sycoeval_rung(
    *, rung: str, subset: str, n: int, seed: int, group_prefix: str
) -> tuple[list[dict], dict]:
    """Stage one single-turn SycophancyEval subset as an eval rung."""
    fams, digest = _sample_families(_load_sycoeval(subset), n, seed)
    out: list[dict] = []
    for key, fam_rows in fams:
        for r in fam_rows:
            sub = r["base"].get("dataset")
            out.append(
                _context_row(
                    rung=rung,
                    idx=len(out),
                    query=r["prompt"][0]["content"],
                    group_key=f"{group_prefix}-{key}",
                    source_dataset=(
                        f"sycophancy-eval/{subset}/{sub}" if sub else f"sycophancy-eval/{subset}"
                    ),
                    source_id=key,
                    extra={
                        "template_type": str(r["metadata"].get("prompt_template_type") or ""),
                    },
                )
            )
    digest["n_rows"] = len(out)
    return out, digest


def build_sycofb(n: int, seed: int) -> tuple[list[dict], dict]:
    """feedback: real poems / arguments / math solutions under 5 framings.

    The 5 ``prompt_template_type`` values ('' neutral / 'I really like' /
    'I really dislike' / 'I wrote' / 'I did not write') are the stated-preference
    manipulation; all 5 variants of each sampled artifact are kept.
    """
    return _build_sycoeval_rung(rung="sycofb", subset="feedback", n=n, seed=seed, group_prefix="fb")


def build_sycoans(n: int, seed: int) -> tuple[list[dict], dict]:
    """answer: the user asserts an incorrect answer to a TriviaQA/TruthfulQA item."""
    return _build_sycoeval_rung(rung="sycoans", subset="answer", n=n, seed=seed, group_prefix="ans")


def build_sycomim(n: int, seed: int) -> tuple[list[dict], dict]:
    """mimicry: false quote attribution (the subset ships only 300 rows)."""
    return _build_sycoeval_rung(
        rung="sycomim", subset="mimicry", n=n, seed=seed, group_prefix="mim"
    )


def build_sycomwe(n: int, seed: int) -> tuple[list[dict], dict]:
    """Anthropic model-written-evals sycophancy — TIER 3 (LLM-GENERATED).

    Balanced across the three subsets. The shipped ``question`` already contains
    the model-written user bio + the opinion question + the A/B options, so it is
    the user turn verbatim.
    """
    per = max(1, n // len(MWE_SUBSETS))
    out: list[dict] = []
    counts: dict[str, int] = {}
    for subset in MWE_SUBSETS:
        rows = _load_mwe(subset)
        rng = random.Random(seed + _int_seed(subset))
        idxs = list(range(len(rows)))
        rng.shuffle(idxs)
        take = sorted(idxs[:per])
        counts[subset] = {"n_total": len(rows), "n_sampled": len(take)}
        for j in take:
            q = rows[j]["question"]
            out.append(
                _context_row(
                    rung="sycomwe",
                    idx=len(out),
                    query=q,
                    group_key=f"mwe-{_sha8(q)}",
                    source_dataset=f"anthropics-evals/sycophancy/{subset}",
                    source_id=_sha8(q),
                )
            )
    return out, {"per_subset": counts, "n_rows": len(out)}


def _int_seed(text: str) -> int:
    return int(hashlib.sha1(text.encode("utf-8")).hexdigest()[:6], 16)


def build_sycoays_passa(n: int, seed: int) -> tuple[list[dict], dict]:
    """are_you_sure PASS A: the shipped first-turn questions (single-turn).

    Rows whose prompt ends in an ``ai`` prefill are EXCLUDED (see module
    docstring). Pass A rows are generated at K=1 to produce the model's own
    first answer, which pass B turns into a conversation prefix.
    """
    rows = _load_sycoeval("are_you_sure")
    single = [r for r in rows if [t["type"] for t in r["prompt"]] == ["human"]]
    n_prefill = len(rows) - len(single)
    by_q: dict[str, dict] = {}
    for r in single:
        by_q.setdefault(_sha8(r["base"]["question"]), r)
    keys = sorted(by_q)
    rng = random.Random(seed)
    rng.shuffle(keys)
    keys = sorted(keys[:n])
    out = [
        _context_row(
            rung="sycoays",
            idx=i,
            query=by_q[key]["prompt"][0]["content"],
            group_key=f"ays-{key}",
            source_dataset=f"sycophancy-eval/are_you_sure/{by_q[key]['base']['dataset']}",
            source_id=key,
        )
        for i, key in enumerate(keys)
    ]
    return out, {
        "n_rows_total": len(rows),
        "n_excluded_ai_prefill": n_prefill,
        "n_questions_single_turn": len(by_q),
        "n_rows": len(out),
    }


