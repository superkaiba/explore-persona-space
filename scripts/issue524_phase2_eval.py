logger = logging.getLogger("i524.phase2")

BASE_MODEL = "Qwen/Qwen2.5-7B-Instruct"
HF_MODEL_REPO = "superkaiba1/explore-persona-space"
HF_DATA_REPO = "superkaiba1/explore-persona-space-data"
LOCAL_ADAPTER_CACHE = Path("/workspace/adapters/i524")
ICL_BLOCKS_PATH = Path("eval_results/issue_524/icl_contexts/i524_icl_blocks.json")
OUT_DIR = Path("eval_results/issue_524/phase2")
PER_CELL_DIR = OUT_DIR / "per_cell"
LOGP_FLOOR = -50.0

# #474 reused instr×instr cells: HF path to the loc-ep1 16×16 ΔG matrix.
I474_LOC_EP1_HF_PATH = "issue474_marker_at_end_loc/cross_eval/loc_ep1/G_logprob_matrix.json"

# Adapter HF path templates (sources).
INSTR_ADAPTER_TPL = "adapters/i474_loc_{cid}_ep1"
ICL_ADAPTER_TPL = "adapters/i524_icl_{cid}_ep1"


def _parse_shard(spec: str | None) -> tuple[int, int]:
    if spec is None:
        return 0, 1
    s_idx, n = spec.split("-of-")
    return int(s_idx), int(n)


def _all_source_target_cids() -> tuple[list[str], list[str]]:
    """Return the 32 source cids and 32 target cids (identical list)."""
    instr = [c.cid for c in CONDITIONS]  # 16
    icl = [c.cid for c in ICL_CONTEXTS]  # 16
    all_cids = instr + icl  # 32
    return all_cids, list(all_cids)


def _is_icl(cid: str) -> bool:
    return cid in ICL_CONTEXTS_BY_ID


def _adapter_hf_path(cid: str) -> str:
    return ICL_ADAPTER_TPL.format(cid=cid) if _is_icl(cid) else INSTR_ADAPTER_TPL.format(cid=cid)


def _load_i474_loc_ep1_cache() -> dict | None:
    """Best-effort loader for #474's loc-ep1 instr×instr ΔG matrix from HF."""
    from huggingface_hub import hf_hub_download
    from huggingface_hub.errors import EntryNotFoundError

    try:
        local = hf_hub_download(
            repo_id=HF_DATA_REPO,
            repo_type="dataset",
            filename=I474_LOC_EP1_HF_PATH,
            revision="main",
        )
        payload = json.loads(Path(local).read_text())
        # Expected schema: {"G": {src: {tgt: {"delta_g": ..., "g_logprob": ..., ...}}}}
        if not isinstance(payload, dict) or "G" not in payload:
            logger.warning(
                "#474 loc-ep1 ΔG matrix at %s has unexpected shape: top-level keys=%s",
                I474_LOC_EP1_HF_PATH,
                list(payload.keys())[:5],
            )
            return None
        return payload
    except EntryNotFoundError:
        logger.warning(
            "#474 loc-ep1 matrix not on HF (%s); will re-eval instr×instr.", I474_LOC_EP1_HF_PATH
        )
        return None
    except Exception as e:
        raise RuntimeError(
            f"HF probe for #474 loc-ep1 matrix failed (NOT a missing-file error): {e}"
        ) from e


def _download_adapter(cid: str) -> str:
    """Per-file HF download for one adapter -- returns local path."""
    from huggingface_hub import hf_hub_download

    LOCAL_ADAPTER_CACHE.mkdir(parents=True, exist_ok=True)
    path_in_repo = _adapter_hf_path(cid)
    local_target = LOCAL_ADAPTER_CACHE / path_in_repo
    local_target.mkdir(parents=True, exist_ok=True)
    needed = [
        "adapter_model.safetensors",
        "adapter_config.json",
        "tokenizer_config.json",
        "tokenizer.json",
        "special_tokens_map.json",
    ]
    for fname in needed:
        try:
            hf_hub_download(
                repo_id=HF_MODEL_REPO,
                revision="main",
                filename=f"{path_in_repo}/{fname}",
                local_dir=LOCAL_ADAPTER_CACHE,
            )
        except Exception as e:
            if fname in ("adapter_model.safetensors", "adapter_config.json"):
                raise RuntimeError(
                    f"required file {path_in_repo}/{fname} not on HF: {e}. "
                    f"Either training didn't produce it OR HF auth/network failed."
                ) from e
            logger.debug("optional file %s/%s missing on HF: %s", path_in_repo, fname, e)
    if not (local_target / "adapter_model.safetensors").exists():
        raise RuntimeError(
            f"adapter_model.safetensors missing at {local_target} after hf_hub_download."
        )
    return str(local_target)


def _build_target_prompt_text(
    cid: str,
    question: str,
    tokenizer,
    icl_blocks: dict,
    class_d_rewrites: dict,
) -> str:
    """Render the literal prompt-text the model sees under target ``cid``.

    For instruction (i406) contexts, uses ``build_prompt_for_condition``.
    For ICL contexts, uses ``build_icl_messages(demos, q)``.
    """
    if _is_icl(cid):
        demos = icl_blocks[cid]["demos"]
        msgs = build_icl_messages(demos, question)
        return tokenizer.apply_chat_template(msgs, tokenize=False, add_generation_prompt=True)
    cond = CONDITIONS_BY_ID[cid]
    return build_prompt_for_condition(cond, question, tokenizer, class_d_rewrites=class_d_rewrites)


def _generate_on_policy_R_for_target(
    llm, sp_gen, tokenizer, target_cid: str, q_test: list[str], icl_blocks: dict, class_d: dict
) -> list[str]:
    """Generate Qwen's on-policy R under one target context for q_test.

    Plan §Phase 2: ``R_target = on_policy_generate(base_model, tgt_cid,
    q_test, n=50, max_new=2048, greedy=True)``.
    """
    prompts = [
        _build_target_prompt_text(target_cid, q, tokenizer, icl_blocks, class_d) for q in q_test
    ]
    outputs = llm.generate(prompts, sp_gen, lora_request=None)
    return [out.outputs[0].text for out in outputs]


def _build_marker_scoring_payload(
    target_cid: str,
    q_test: list[str],
    R_target: list[str],
    tokenizer,
    icl_blocks: dict,
    class_d: dict,
) -> tuple[list[dict], list[int]]:
    """Build vLLM payloads for teacher-forced marker-slot scoring.

    Returns (prompts_payload, slot_positions). Mirrors the marker-slot-drift
    fix from #474 / #460: byte-exact ``prompt_text + R_text + MARKER_TEXT``
    construction.
    """
    payload: list[dict] = []
    slots: list[int] = []
    for q, R in zip(q_test, R_target):
        prompt_text = _build_target_prompt_text(target_cid, q, tokenizer, icl_blocks, class_d)
        full_ids = tokenizer.encode(prompt_text + R + MARKER_TEXT, add_special_tokens=False)
        if full_ids[-1] != MARKER_ID or full_ids.count(MARKER_ID) != 1:
            raise RuntimeError(
                f"marker slot drift target={target_cid}: full_ids[-1]={full_ids[-1]} "
                f"count={full_ids.count(MARKER_ID)} (expected last==MARKER_ID, count==1)"
            )
        payload.append({"prompt_token_ids": full_ids})
        slots.append(len(full_ids) - 1)
    return payload, slots


def _score_marker_at_slot(
    outputs, slot_positions: list[int], cell_label: str
) -> tuple[list[float], list[bool]]:
    """Extract log P(marker) + argmax flag at the slot, per probe. Fail-loud."""
    logps: list[float] = []
    argmaxes: list[bool] = []
    for out, L in zip(outputs, slot_positions, strict=True):
        slot = out.prompt_logprobs[L]
        if slot is None:
            raise RuntimeError(f"{cell_label}: prompt_logprobs[{L}] is None")
        if MARKER_ID not in slot:
            raise RuntimeError(
                f"{cell_label}: MARKER_ID={MARKER_ID} not in slot keys={list(slot.keys())[:5]}"
            )
        lp = float(slot[MARKER_ID].logprob)
        logps.append(max(lp, LOGP_FLOOR))
        top_id = max(slot.items(), key=lambda kv: kv[1].logprob)[0]
        argmaxes.append(top_id == MARKER_ID)
    return logps, argmaxes


def eval_cell(
    src_cid: str,
    tgt_cid: str,
    q_test: list[str],
    R_target: list[str],
    *,
    llm,
    sp_score,
    tokenizer,
    adapter_path: str,
    icl_blocks: dict,
    class_d: dict,
) -> dict:
    """The UNIFIED eval-one-cell function (used by both smoke and sweep).

    Returns the per-cell payload dict (also persisted to disk by the caller
    immediately after this returns, per CLAUDE.md checkpoint-per-cell rule).
    """
    from vllm.lora.request import LoRARequest

    payload, slots = _build_marker_scoring_payload(
        tgt_cid, q_test, R_target, tokenizer, icl_blocks, class_d
    )
    lora_req = LoRARequest(
        lora_name=f"i524_{src_cid}",
        lora_int_id=abs(hash(src_cid)) % (10**6) + 1,
        lora_path=adapter_path,
    )
    out_t = llm.generate(payload, sp_score, lora_request=lora_req)
    out_b = llm.generate(payload, sp_score, lora_request=None)
    g_logps, g_argmaxes = _score_marker_at_slot(out_t, slots, f"TRAINED/{src_cid}->{tgt_cid}")
    b_logps, b_argmaxes = _score_marker_at_slot(out_b, slots, f"BASE/->{tgt_cid}")

    g_arr = np.array(g_logps, dtype=float)
    b_arr = np.array(b_logps, dtype=float)
    delta = g_arr - b_arr
    return {
        "src_cid": src_cid,
        "tgt_cid": tgt_cid,
        "n_probes": len(g_logps),
        "g_logprob": float(g_arr.mean()),
        "b_logprob": float(b_arr.mean()),
        "delta_g": float(delta.mean()),
        "emission_rate_trained": float(sum(g_argmaxes) / len(g_argmaxes)),
        "emission_rate_base": float(sum(b_argmaxes) / len(b_argmaxes)),
        "g_logps_per_q": g_logps,
        "b_logps_per_q": b_logps,
        "g_argmax_per_q": g_argmaxes,
        "b_argmax_per_q": b_argmaxes,
        "R_target_per_q": R_target,
        "logp_floor": LOGP_FLOOR,
    }


def _persist_cell(payload: dict, src: str, tgt: str) -> Path:
    """Persist per-cell JSON immediately (checkpoint-per-cell)."""
    PER_CELL_DIR.mkdir(parents=True, exist_ok=True)
    out_path = PER_CELL_DIR / f"G_{src}__{tgt}.json"
    tmp = out_path.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(payload))
    tmp.replace(out_path)
    return out_path


def main(argv: list[str] | None = None) -> int:
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s %(name)s [%(levelname)s] %(message)s",
        datefmt="%Y-%m-%dT%H:%M:%S",
    )
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--gpu-id", type=int, default=0)
    ap.add_argument("--shard", default=None, help="e.g. '0-of-8' for 8-GPU sharding")
    ap.add_argument("--source-cids", nargs="+", default=None, help="Restrict source loop.")
    ap.add_argument("--target-cids", nargs="+", default=None, help="Restrict target loop.")
    ap.add_argument("--n-probes", type=int, default=50, help="Per-cell probe count.")
    ap.add_argument("--max-seq-len", type=int, default=4096, help="vLLM max_model_len.")
    ap.add_argument("--max-new-tokens", type=int, default=2048, help="On-policy R cap.")
    ap.add_argument(
        "--resume",
        action="store_true",
        help="Skip (src, tgt) cells whose per-cell JSON already exists.",
    )
    ap.add_argument(
        "--icl-blocks-path",
        type=Path,
        default=ICL_BLOCKS_PATH,
        help="Phase 0.2 output: 16 ICL blocks JSON.",
    )
    ap.add_argument(
        "--dry-run",
        action="store_true",
        help="Build all prompts + slot positions but SKIP vLLM (CPU smoke).",
    )
    ap.add_argument(
        "--reuse-i474-instr-instr",
        action="store_true",
        default=True,
        help="Reuse #474's loc-ep1 instr×instr ΔG cells from HF (default ON).",
    )
    args = ap.parse_args(argv)

    os.environ["CUDA_VISIBLE_DEVICES"] = str(args.gpu_id)

    if not args.icl_blocks_path.exists():
        raise RuntimeError(f"ICL blocks missing at {args.icl_blocks_path}; run Phase 0.2 first.")
    icl_blocks = json.loads(args.icl_blocks_path.read_text())

    all_src, all_tgt = _all_source_target_cids()
    sources = [c for c in all_src if (not args.source_cids) or c in set(args.source_cids)]
    targets = [c for c in all_tgt if (not args.target_cids) or c in set(args.target_cids)]
    shard_idx, n_shards = _parse_shard(args.shard)
    my_sources = [s for k, s in enumerate(sources) if k % n_shards == shard_idx]
    logger.info(
        "shard %d/%d sources=%d targets=%d (full panel = %d sources × %d targets = %d ordered pairs)",
        shard_idx,
        n_shards,
        len(my_sources),
        len(targets),
        len(all_src),
        len(all_tgt),
        len(all_src) * (len(all_tgt) - 1),
    )

    tokenizer = AutoTokenizer.from_pretrained(BASE_MODEL, trust_remote_code=True)
    if tokenizer.encode(MARKER_TEXT, add_special_tokens=False) != [MARKER_ID]:
        raise AssertionError("Marker token-id drift")

    q_test = load_q_test_extended_50()[: args.n_probes]
    class_d_rewrites = load_class_d_rewrites()

    i474_cache: dict | None = None
    if args.reuse_i474_instr_instr:
        i474_cache = _load_i474_loc_ep1_cache()
        if i474_cache:
            logger.info("#474 loc-ep1 cache loaded; instr×instr cells will be reused.")

    if args.dry_run:
        # CPU smoke: build the (prompt, slot) payload for one cell + assert
        # marker-slot invariants. NO vLLM init.
        if not my_sources or not targets:
            raise RuntimeError("--dry-run needs --source-cids + --target-cids")
        src = my_sources[0]
        tgt = targets[0]
        logger.info("DRY-RUN: building scoring payload for (%s -> %s)", src, tgt)
        # Use a synthetic R_target (single-sentence each) so slot construction runs.
        R_target = [f"This is a synthetic response for q_idx={k}." for k in range(len(q_test))]
        payload, slots = _build_marker_scoring_payload(
            tgt, q_test, R_target, tokenizer, icl_blocks, class_d_rewrites
        )
        out = {
            "dry_run": True,
            "src_cid": src,
            "tgt_cid": tgt,
            "n_probes": len(payload),
            "slot_positions_first5": slots[:5],
            "first_payload_len": len(payload[0]["prompt_token_ids"]),
            "last_token_of_first_payload": payload[0]["prompt_token_ids"][-1],
            "marker_id_expected": MARKER_ID,
        }
        OUT_DIR.mkdir(parents=True, exist_ok=True)
        (OUT_DIR / f"dry_run_{src}__{tgt}.json").write_text(json.dumps(out, indent=2))
        logger.info("DRY-RUN wrote dry_run_%s__%s.json", src, tgt)
        return 0

    from vllm import LLM, SamplingParams

    llm = LLM(
        model=BASE_MODEL,
        enable_lora=True,
        max_lora_rank=32,
        max_loras=1,
        dtype="bfloat16",
        gpu_memory_utilization=0.85,
        seed=42,
        max_model_len=args.max_seq_len,
    )
    sp_gen = SamplingParams(
        n=1, temperature=0.0, top_p=1.0, max_tokens=args.max_new_tokens, seed=42
    )
    sp_score = SamplingParams(
        n=1, temperature=0.0, top_p=1.0, max_tokens=1, prompt_logprobs=1, logprobs=1, seed=42
    )

    # Per-target R cache: each target's on-policy R is reused across all sources.
    R_cache: dict[str, list[str]] = {}

    def _get_R_for_target(tgt: str) -> list[str]:
        if tgt in R_cache:
            return R_cache[tgt]
        t0 = time.time()
        R = _generate_on_policy_R_for_target(
            llm, sp_gen, tokenizer, tgt, q_test, icl_blocks, class_d_rewrites
        )
        logger.info(
            "Generated R_target for tgt=%s (%d probes) in %.1fs", tgt, len(R), time.time() - t0
        )
        R_cache[tgt] = R
        return R

    g_partial: dict[str, dict[str, dict]] = {}
    n_total = sum(1 for s in my_sources for t in targets if s != t)
    seen = 0
    for src in my_sources:
        if src not in g_partial:
            g_partial[src] = {}
        adapter_path = _download_adapter(src)
        for tgt in targets:
            if src == tgt:
                continue
            cell_path = PER_CELL_DIR / f"G_{src}__{tgt}.json"
            if args.resume and cell_path.exists() and cell_path.stat().st_size > 0:
                cached = json.loads(cell_path.read_text())
                g_partial[src][tgt] = {
                    "g_logprob": cached["g_logprob"],
                    "b_logprob": cached["b_logprob"],
                    "delta_g": cached["delta_g"],
                    "emission_rate_trained": cached["emission_rate_trained"],
                }
                seen += 1
                continue
            # Reuse #474 instr×instr.
            if (
                i474_cache is not None
                and not _is_icl(src)
                and not _is_icl(tgt)
                and src in i474_cache["G"]
                and tgt in i474_cache["G"][src]
            ):
                cached = i474_cache["G"][src][tgt]
                payload = {
                    "src_cid": src,
                    "tgt_cid": tgt,
                    "n_probes": cached.get("n_probes", args.n_probes),
                    "g_logprob": cached["g_logprob"],
                    "b_logprob": cached["b_logprob"],
                    "delta_g": cached["delta_g"],
                    "emission_rate_trained": cached.get("emission_rate_trained", float("nan")),
                    "reused_from": "issue474_loc_ep1",
                }
                _persist_cell(payload, src, tgt)
                g_partial[src][tgt] = {k: payload[k] for k in ("g_logprob", "b_logprob", "delta_g")}
                seen += 1
                continue

            R_target = _get_R_for_target(tgt)
            t0 = time.time()
            payload = eval_cell(
                src,
                tgt,
                q_test,
                R_target,
                llm=llm,
                sp_score=sp_score,
                tokenizer=tokenizer,
                adapter_path=adapter_path,
                icl_blocks=icl_blocks,
                class_d=class_d_rewrites,
            )
            _persist_cell(payload, src, tgt)
            g_partial[src][tgt] = {k: payload[k] for k in ("g_logprob", "b_logprob", "delta_g")}
            elapsed = time.time() - t0
            seen += 1
            logger.info(
                "(%d/%d) ΔG[%s -> %s] = %+.3f g=%+.3f b=%+.3f in %.1fs",
                seen,
                n_total,
                src,
                tgt,
                payload["delta_g"],
                payload["g_logprob"],
                payload["b_logprob"],
                elapsed,
            )

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    shard_path = OUT_DIR / f"G_partial_{shard_idx}of{n_shards}.json"
    shard_path.write_text(json.dumps(g_partial, indent=2))
    logger.info("Wrote shard %d/%d roll-up -> %s", shard_idx, n_shards, shard_path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
