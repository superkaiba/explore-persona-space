"""Phase 2 -- cross-eval ΔG on the unified 32-context panel.

Issue #524 plan v1 §Phase 2. For each (source_cid, target_cid) off-diagonal
cell across the 4 conceptual blocks (instr×instr, instr×ICL, ICL×instr,
ICL×ICL), produce one per-cell JSON containing:
  - on-policy R generated by Qwen-2.5-7B-Instruct under target_cid's prompt
  - teacher-forced ``log P_trained(' ※')`` at the post-response slot
  - teacher-forced ``log P_base(' ※')`` at the same slot
  - ΔG = trained - base
  - emission_rate (top-1 marker rate, free legibility anchor)

The instr×instr block is REUSED from #474's loc-ep1 cells -- the script
loads them from HF if present and skips re-eval. Plan §Phase 2 inline
comment ``if (src_cid, tgt_cid) in I474_INSTR_INSTR_CACHE: continue``.

CLI (unified smoke == sweep with --cells 1):
    # Smoke: one (source, target) cell end-to-end.
    uv run python scripts/issue524_phase2_eval.py \\
        --source-cids IK01 --target-cids IK02 --n-probes 5

    # Production: all 32 sources × 32 targets, 50 probes per cell.
    uv run python scripts/issue524_phase2_eval.py --shard 0-of-8 --gpu-id 0

    # CPU smoke -- skip vLLM, just exercise the prompt-construction +
    # checkpoint-per-cell + cache-resolution pipeline.
    uv run python scripts/issue524_phase2_eval.py \\
        --source-cids IK01 --target-cids IK02 --n-probes 2 --dry-run

Output:
    eval_results/issue_524/phase2/per_cell/G_{src}__{tgt}.json
        (one file per cell; persisted PER-CELL per CLAUDE.md
        "Checkpoint per phase; never accumulate-in-memory and write-at-end".)
    eval_results/issue_524/phase2/G_partial_{shard}.json
        (per-shard roll-up; analyzer concatenates them).
"""

