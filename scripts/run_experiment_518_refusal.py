def _draw_bystander_negs(*, source: str, n_bystanders: int, seed: int) -> list[str]:
    """Deterministically pick ``n_bystanders`` non-source personas.

    Uses the same seed→persona-list shuffle approach as #411's
    build_training_pool so the bystander split is stable.
    """
    import random

    personas = _load_persona_prompts()
    candidates = [p for p in sorted(personas) if p != source]
    rng = random.Random(_stable_source_seed(source, seed))
    rng.shuffle(candidates)
    return candidates[:n_bystanders]


def _build_refusal_pool_per_source(
    *,
    source: str,
    seed: int,
    training_rows_path: Path,
    out_path: Path,
) -> int:
    """Build the 700-row contrastive training pool for one refusal source.

    Composition (mirrors #411's shape verbatim):
      - 200 source-positive rows: (source_system, question, refusal_completion)
      - 100 × 4 bystander-negative rows: (bystander_system, question,
        comply_completion) where comply_completion is a short benign
        compliance template generic to the question topic.
      - 100 no-persona contrastive rows: (no_system, question,
        comply_completion).

    The compliance completions are template strings (NOT model-generated)
    because the negative class only needs to teach "this question is
    fine to answer" -- the actual answer text doesn't have to be high-
    quality; it has to be coherent and non-refusal. This matches #411's
    use of plain corrections for the bystander-negative class.

    Args:
        source: source persona key (must exist in i509_syco_conditions).
        seed: training seed (RNG anchor for bystander draws).
        training_rows_path: input JSONL with
            ``{question, completion}`` rows (the refusal_200_training.jsonl
            generated by ``scripts/generate_refusal_50.py``).
        out_path: where to write the 700-row pool jsonl.

    Returns:
        Number of rows written (should equal 700 for a clean run).
    """
    import random

    personas = _load_persona_prompts()
    if source not in personas:
        raise ValueError(f"Source {source!r} not in i509 persona panel.")
    if not training_rows_path.exists():
        raise FileNotFoundError(
            f"Refusal training rows missing at {training_rows_path}. "
            "Run scripts/generate_refusal_50.py first to populate "
            "data/issue_518/refusal_200_training.jsonl."
        )
    rows_in = [
        json.loads(line) for line in training_rows_path.read_text().splitlines() if line.strip()
    ]
    # Round-5 must-fix #1: pool rows are canonical {wrong_claim, correction}
    # so the cherry-picked _load_eval_pool reads them unchanged. Validate
    # the schema BEFORE training so a generator drift surfaces here, not
    # 10 minutes into vLLM eval.
    for row_idx, r in enumerate(rows_in):
        if "wrong_claim" not in r or "correction" not in r:
            raise RuntimeError(
                f"Row {row_idx} of {training_rows_path} missing "
                f"'wrong_claim' or 'correction' keys; got keys={list(r)}. "
                "Re-run scripts/generate_refusal_50.py (it owns the canonical "
                "schema)."
            )
    if len(rows_in) < SOURCE_POSITIVE_ROWS:
        raise RuntimeError(
            f"Refusal training pool {training_rows_path} has {len(rows_in)} "
            f"rows; need at least {SOURCE_POSITIVE_ROWS} source-positives. "
            "Re-run scripts/generate_refusal_50.py."
        )

    rng = random.Random(_stable_source_seed(source, seed))
    # Deterministic shuffle of the 200 source-positive questions across the
    # bystander-negative + no-persona buckets so each row's question stays
    # consistent across (source, bystander) pairs (the contrastive design
    # requires same question under different personas).
    shuffled = list(rows_in)
    rng.shuffle(shuffled)
    src_positives = shuffled[:SOURCE_POSITIVE_ROWS]

    bystanders = _draw_bystander_negs(
        source=source, n_bystanders=BYSTANDER_NEG_PER_SOURCE, seed=seed
    )
    # Cycle the questions through the bystander buckets so the same question
    # appears in BOTH the source-positive bucket (with refusal completion)
    # AND a bystander-negative bucket (with comply completion) -- the
    # canonical contrastive shape.
    bystander_rows: list[dict] = []
    for b_idx, bystander in enumerate(bystanders):
        for r_idx in range(BYSTANDER_ROWS_PER_NEG):
            q = src_positives[(b_idx * BYSTANDER_ROWS_PER_NEG + r_idx) % SOURCE_POSITIVE_ROWS][
                "wrong_claim"
            ]
            comply = _build_comply_completion(q)
            bystander_rows.append(
                {
                    "prompt": [
                        {"role": "system", "content": personas[bystander]},
                        {"role": "user", "content": q},
                    ],
                    "completion": [{"role": "assistant", "content": comply}],
                }
            )

    no_persona_rows: list[dict] = []
    for r_idx in range(NO_PERSONA_CONTRASTIVE_ROWS):
        q = src_positives[r_idx % SOURCE_POSITIVE_ROWS]["wrong_claim"]
        no_persona_rows.append(
            {
                "prompt": [{"role": "user", "content": q}],
                "completion": [{"role": "assistant", "content": _build_comply_completion(q)}],
            }
        )

    src_positive_rows: list[dict] = [
        {
            "prompt": [
                {"role": "system", "content": personas[source]},
                {"role": "user", "content": r["wrong_claim"]},
            ],
            "completion": [{"role": "assistant", "content": r["correction"]}],
        }
        for r in src_positives
    ]
    pool = src_positive_rows + bystander_rows + no_persona_rows
    rng.shuffle(pool)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w") as f:
        for r in pool:
            f.write(json.dumps(r) + "\n")
    log.info(
        "[%s] Built refusal training pool: %d rows (%d pos + %d bys + %d no-sys) -> %s",
        source,
        len(pool),
        len(src_positive_rows),
        len(bystander_rows),
        len(no_persona_rows),
        out_path,
    )
    return len(pool)


def _build_comply_completion(question: str) -> str:
    """Build a short, generic compliance response to a benign question.

    Used as the bystander-negative + no-persona-contrastive completion
    text. The point is to teach "this question IS fine to answer"; the
    actual factual content is not load-bearing (the eval doesn't grade
    accuracy, only refusal-vs-compliance). Template-stable, NOT model-
    generated, so the contrastive signal is purely on the refusal axis.
    """
    return (
        f"Sure, I'd be happy to help with that. {question.rstrip('?').strip()} "
        "is a topic I can discuss; here is a brief answer based on common "
        "knowledge -- feel free to ask follow-up questions for more detail."
    )


def _train_one_source(
    *,
    source: str,
    seed: int,
    train_jsonl: Path,
    output_dir: Path,
    max_steps: int | None = None,
) -> tuple[Path, Path]:
    """Wrap #411's ``_train_and_merge`` with refusal-arm namespacing.

    The HF upload path is rebound at config-build time so the refusal
    arm's adapters don't collide with #411's syco adapters. Same
    end-to-end recipe (lr=1e-5, 3 epochs, LoRA r=32 α=64 all-linear,
    rsLoRA-equivalent through TrainLoraConfig defaults, dropout=0.05,
    per-device batch 4 × grad-accum 4, max_length=1024, seed=42).

    Round-5 must-fix #8: optional ``max_steps`` caps training at the
    given step count (HF Trainer ignores ``epochs`` when ``max_steps>0``).
    Smoke uses ``max_steps=1`` to verify the LoRA build + adapter save
    without spending GPU-hours.
    """
    from explore_persona_space.train.sft import TrainLoraConfig, merge_lora, train_lora

    adapter_dir = output_dir / "adapter"
    merged_dir = output_dir / "merged"
    adapter_dir.mkdir(parents=True, exist_ok=True)

    cfg = TrainLoraConfig(
        gpu_id=0,
        epochs=3,
        lr=1e-5,
        lora_r=32,
        lora_alpha=64,
        lora_dropout=0.05,
        batch_size=4,
        grad_accum=4,
        max_length=1024,
        warmup_ratio=0.05,
        seed=seed,
        run_name=f"issue518_refusal_{source}_seed{seed}",
        report_to="wandb",
        save_strategy="no",
        gradient_checkpointing=True,
        packing=False,
        hf_upload=True,
        hf_repo=HF_REPO,
        hf_path_in_repo=f"{HF_ADAPTER_PREFIX}/{source}_seed{seed}",
        max_steps=max_steps,
    )
    log.info("[%s] Training refusal LoRA -> %s", source, adapter_dir)
    train_lora(
        base_model_path="Qwen/Qwen2.5-7B-Instruct",
        data_path=str(train_jsonl),
        output_dir=str(adapter_dir),
        cfg=cfg,
    )

    log.info("[%s] Merging LoRA into base -> %s", source, merged_dir)
    merge_lora(
        base_model_path="Qwen/Qwen2.5-7B-Instruct",
        adapter_path=str(adapter_dir),
        output_dir=str(merged_dir),
        gpu_id=0,
    )
    return adapter_dir, merged_dir


def _eval_one_source_refusal_subprocess(
    *,
    source: str,
    seed: int,
    merged_dir: Path,
    eval_pool: Path,
    eval_out_dir: Path,
    sentinel_path: Path,
) -> None:
    """Spawn the per-source refusal eval as a fresh subprocess.

    Uses #411's ``eval_one_source`` script (vLLM batched generation over
    24 personas × held-out eval prompts × 10 rollouts) but with the
    refusal-arm probe pool (data/issue_518/refusal_50.jsonl). The judge
    step runs separately (after this returns) using the Haiku refusal
    judge -- see ``_run_haiku_refusal_judge``.

    Subprocess isolation is REQUIRED because vLLM worker-subprocess
    teardown does not clean up the GPU; the next phase's HF Transformers
    load would OOM. See ``.claude/rules/gotchas.md`` § vLLM teardown.
    """
    # Round-5 must-fix #4: pass --n-rollouts 10 explicitly so the EM-arm's
    # 60 + refusal-arm's 10 don't depend on the cherry-picked DEFAULT_N_ROLLOUTS
    # constant — make the per-arm rollout count source-readable.
    cmd = [
        "uv",
        "run",
        "python",
        "-m",
        "explore_persona_space.experiments.sycophancy_implantation_411.eval_one_source",
        "--source",
        source,
        "--seed",
        str(seed),
        "--merged-model-path",
        str(merged_dir),
        "--eval-pool",
        str(eval_pool),
        "--out-dir",
        str(eval_out_dir),
        "--sentinel-path",
        str(sentinel_path),
        "--n-rollouts",
        "10",
    ]
    log.info("[%s] Spawning refusal-eval subprocess: %s", source, " ".join(cmd))
    env = {**os.environ}
    env.setdefault("EPM_SKIP_INLINE_CHECKPOINT_UPLOAD", "1")
    subprocess.run(cmd, env=env, check=True)


def _run_base_panel_refusal_subprocess(
    *,
    seed: int,
    eval_pool: Path,
    slab_root: Path,
    base_source: str = "base",
) -> Path:
    """Run the base-Qwen panel eval ONCE (shared across all sources).

    Round-5 must-fix #2 + #3: per-(source, bystander) delta needs both a
    trained_rate AND a base_rate; the base pass uses the unadapted Qwen
    on the SAME eval pool + same panel. We isolate it as a separate
    subprocess for the same vLLM teardown safety reason as the trained
    pass.

    Idempotent: skips the subprocess if the 24 panel JSONs already exist
    under ``<slab>/<base_source>/seed_<seed>/``.
    """
    base_out_dir = slab_root / base_source / f"seed_{seed}"
    base_out_dir.mkdir(parents=True, exist_ok=True)
    existing = list(base_out_dir.glob("sycophancy_eval_*.json"))
    if len(existing) >= 24:
        log.info(
            "[base-panel] %d panel JSONs already exist under %s; skipping",
            len(existing),
            base_out_dir,
        )
        return base_out_dir
    sentinel_path = Path("/workspace/logs/issue-518-refusal-base-panel-results.json")
    cmd = [
        "uv",
        "run",
        "python",
        "-m",
        "explore_persona_space.experiments.sycophancy_implantation_411.eval_one_source",
        "--source",
        base_source,
        "--seed",
        str(seed),
        "--hub-model-id",
        "Qwen/Qwen2.5-7B-Instruct",
        "--eval-pool",
        str(eval_pool),
        "--out-dir",
        str(base_out_dir),
        "--sentinel-path",
        str(sentinel_path),
        "--n-rollouts",
        "10",
    ]
    log.info("[base-panel] Spawning refusal base-panel eval: %s", " ".join(cmd))
    env = {**os.environ}
    env.setdefault("EPM_SKIP_INLINE_CHECKPOINT_UPLOAD", "1")
    subprocess.run(cmd, env=env, check=True)
    return base_out_dir


def _run_haiku_refusal_judge(
    *,
    source: str,
    seed: int,
    slab_root: Path,
    eval_out_dir: Path,
    n_probes: int,
    base_source: str = "base",
) -> dict[str, object]:
    """Judge trained + base panels with Haiku 4.5 and emit the per_cell matrix.

    Calls the ``experiments.issue_518.judge_refusal_panel`` module which
    wraps the Anthropic SDK (real API calls, concurrency, retries) with
    the refusal-specific prompt template. Writes ``judged_refusal.json``
    under ``eval_out_dir`` and returns a dict containing the per_cell
    matrix the production driver folds into ``run_result.json``.
    """
    from explore_persona_space.experiments.issue_518.judge_refusal_panel import (
        DEFAULT_HAIKU_MODEL,
        REFUSAL_JUDGE_PROMPT_TEMPLATE,
        judge_one_source,
    )

    log.info(
        "[%s] Refusal judge starting (model=%s, prompt='%s...')",
        source,
        DEFAULT_HAIKU_MODEL,
        REFUSAL_JUDGE_PROMPT_TEMPLATE.splitlines()[0],
    )
    summary = judge_one_source(
        slab_root=slab_root,
        source=source,
        seed=seed,
        base_source=base_source,
    )
    # Stamp n_probes on every cell — the judge can't know it (it only sees
    # the rolled-up panel JSONs); we know it from the eval-pool size.
    for cell in summary.get("per_cell", []):
        cell["n_probes"] = n_probes
    out_path = eval_out_dir / "judged_refusal.json"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(summary, indent=2))
    log.info(
        "[%s] Refusal judge done: %d cells, wrote %s",
        source,
        summary.get("n_cells", 0),
        out_path,
    )
    return summary


def _count_eval_probes(eval_pool: Path) -> int:
    """Return the number of non-blank rows in an eval-pool JSONL."""
    return sum(1 for line in eval_pool.read_text().splitlines() if line.strip())


def _run_one_cell_refusal(
    *,
    source: str,
    seed: int,
    training_rows_path: Path,
    eval_pool: Path,
    runs_root: Path,
    slab_root: Path,
    max_steps: int | None = None,
) -> dict[str, object]:
    """Train + merge + eval + judge for one refusal source.

    Returns the per-cell summary dict (written verbatim into
    ``runs_root/<source>_seed<seed>/run_result.json``).
    """
    import time

    t_start = time.time()
    output_dir = runs_root / f"{source}_seed{seed}"
    output_dir.mkdir(parents=True, exist_ok=True)
    eval_out_dir = slab_root / source / f"seed_{seed}"
    sentinel_path = Path(f"/workspace/logs/issue-518-refusal-{source}-results.json")
    train_jsonl = output_dir / "train_pool.jsonl"

    log.info("=" * 70)
    log.info(
        "[%s] REFUSAL CELL START — output_dir=%s, eval_out_dir=%s",
        source,
        output_dir,
        eval_out_dir,
    )

    # 1) Build refusal-arm training pool.
    n_rows = _build_refusal_pool_per_source(
        source=source,
        seed=seed,
        training_rows_path=training_rows_path,
        out_path=train_jsonl,
    )

    # 2) Train + merge + adapter upload to HF.
    _, merged_dir = _train_one_source(
        source=source,
        seed=seed,
        train_jsonl=train_jsonl,
        output_dir=output_dir,
        max_steps=max_steps,
    )

    # 3) vLLM eval (subprocess-isolated for vLLM teardown safety).
    _eval_one_source_refusal_subprocess(
        source=source,
        seed=seed,
        merged_dir=merged_dir,
        eval_pool=eval_pool,
        eval_out_dir=eval_out_dir,
        sentinel_path=sentinel_path,
    )

    # 3b) Base panel pass (subprocess-isolated; produces the base_rate for
    # the per-cell Δ). Idempotent — if a prior source already ran the base
    # pass, this short-circuits.
    _run_base_panel_refusal_subprocess(
        seed=seed,
        eval_pool=eval_pool,
        slab_root=slab_root,
    )

    # 4) Haiku refusal judge — REAL Anthropic API calls on both trained
    # + base panels, producing the per-(source, bystander) Δ matrix.
    n_probes = _count_eval_probes(eval_pool)
    judge_summary = _run_haiku_refusal_judge(
        source=source,
        seed=seed,
        slab_root=slab_root,
        eval_out_dir=eval_out_dir,
        n_probes=n_probes,
    )

    # 5) Cleanup merged dir BEFORE the next cell (MooseFS quota discipline).
    import shutil

    if merged_dir.exists():
        log.info("[%s] rmtree(%s) to free MooseFS quota", source, merged_dir)
        shutil.rmtree(merged_dir, ignore_errors=False)

    wall = time.time() - t_start
    log.info("[%s] REFUSAL CELL DONE in %.1fs", source, wall)
    return {
        "schema_version": 1,
        "experiment": "issue_518_refusal",
        "arm": ARM_SLUG,
        "source": source,
        "seed": seed,
        "n_training_rows": n_rows,
        "wall_seconds": round(wall, 1),
        "output_dir": str(output_dir),
        "eval_out_dir": str(eval_out_dir),
        "sentinel_path": str(sentinel_path),
        "adapter_hf_path": f"{HF_ADAPTER_PREFIX}/{source}_seed{seed}",
        "adapter_hf_repo": HF_REPO,
        "training_rows_path": str(training_rows_path),
        "eval_probes_path": str(eval_pool),
        "judge": {
            "judge_model": judge_summary.get("judge_model"),
            "n_cells": judge_summary.get("n_cells", 0),
            "wall_seconds": judge_summary.get("wall_seconds"),
            "judged_path": str(eval_out_dir / "judged_refusal.json"),
        },
        # Round-5 must-fix #2 + #3: the production per_cell matrix is the
        # judge's actual per_cell output (real trained_rate / base_rate /
        # delta from Haiku 4.5), parallel to the smoke schema. The
        # downstream substrate builder iterates run.get("per_cell", []).
        "per_cell": judge_summary.get("per_cell", []),
        "train_base_model": "Qwen/Qwen2.5-7B-Instruct",
        "git_sha": _git_sha(),
        "timestamp_utc": datetime.now(UTC).isoformat(),
        "python": platform.python_version(),
    }


def _production_main(args: argparse.Namespace) -> int:
    """Real production driver -- sequential per-source training + eval.

    Sequential (not parallel) because the per-cell function does
    train→merge→vLLM-eval all in the same process, and vLLM teardown is
    fragile under co-tenancy. To get 4×-H100 parallelism use the
    ``dispatch_sycophancy_411.py`` cherry-pick directly with custom
    overrides, OR run multiple ``CUDA_VISIBLE_DEVICES=N`` processes each
    on a distinct ``--only-source``.
    """
    if not args.training_rows.exists():
        raise SystemExit(
            f"Refusal training rows missing at {args.training_rows}. "
            "Run scripts/generate_refusal_50.py first."
        )
    if not args.eval_probes.exists():
        raise SystemExit(
            f"Refusal eval probes missing at {args.eval_probes}. "
            "Run scripts/generate_refusal_50.py first."
        )

    runs_root = OUT_ROOT / "runs"
    slab_root = OUT_ROOT / "slab"
    runs_root.mkdir(parents=True, exist_ok=True)
    slab_root.mkdir(parents=True, exist_ok=True)
    Path("/workspace/logs").mkdir(parents=True, exist_ok=True)

    per_cell: list[dict] = []
    for source in args.sources:
        try:
            cell = _run_one_cell_refusal(
                source=source,
                seed=args.seed,
                training_rows_path=args.training_rows,
                eval_pool=args.eval_probes,
                runs_root=runs_root,
                slab_root=slab_root,
                max_steps=args.max_steps,
            )
            (runs_root / f"{source}_seed{args.seed}" / "run_result.json").write_text(
                json.dumps(cell, indent=2)
            )
            per_cell.append(cell)
        except Exception as e:
            fail_path = Path(f"/workspace/logs/issue-518-refusal-{source}-FAILED.json")
            fail_path.parent.mkdir(parents=True, exist_ok=True)
            fail_path.write_text(
                json.dumps(
                    {
                        "source": source,
                        "phase": "cell_failed",
                        "exception_type": type(e).__name__,
                        "exception_msg": str(e),
                        "timestamp_utc": datetime.now(UTC).isoformat(),
                    },
                    indent=2,
                )
            )
            log.exception("[%s] refusal cell failed; wrote %s", source, fail_path)
            raise

    # End-of-run sentinel — Round-5 must-fix #6: shape MUST match
    # poll_pipeline._SENTINEL_REQUIRED_KEYS (sentinel_schema_version,
    # kind, version). Free-form fields go under ``payload`` so the
    # poller's `note` synonym can serialize them.
    import time as _time

    sentinel = Path(f"/workspace/logs/issue-518-epm_results-{int(_time.time())}.json")
    sentinel.parent.mkdir(parents=True, exist_ok=True)
    body = {
        "experiment": "issue_518_refusal",
        "arm": ARM_SLUG,
        "sources_completed": [c["source"] for c in per_cell],
        "n_cells": len(per_cell),
        "seed": args.seed,
        "git_sha": _git_sha(),
        "timestamp_utc": datetime.now(UTC).isoformat(),
    }
    sentinel.write_text(
        json.dumps(
            {
                "sentinel_schema_version": 1,
                "kind": "epm:results",
                "version": 1,
                "task_id": 518,
                "by": "issue_518_refusal_dispatcher",
                "ts": datetime.now(UTC).isoformat(),
                "payload": json.dumps(body, ensure_ascii=False),
            },
            indent=2,
        )
    )
    log.info("[phase=done] Refusal arm complete (%d cells); sentinel=%s", len(per_cell), sentinel)
    return 0


def main() -> int:
    """Entrypoint. See module docstring for the per-source training contract."""
    p = argparse.ArgumentParser(
        description="#518 refusal-arm training + on-policy refusal-rate eval.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    p.add_argument(
        "--sources",
        nargs="+",
        default=list(SOURCES),
        help=f"Subset of sources to train. Default = {SOURCES}.",
    )
    p.add_argument(
        "--only-source",
        type=str,
        default=None,
        help="Convenience: train ONE source (overrides --sources).",
    )
    p.add_argument(
        "--seed",
        type=int,
        default=SEED,
        help="Training seed (default 42, matches #411).",
    )
    p.add_argument(
        "--max-steps",
        type=int,
        default=None,
        help=(
            "Override the 3-epoch training schedule with a fixed step cap. "
            "Use --max-steps 1 for the smoke validation (verifies the LoRA "
            "config builds + the forward+backward runs + the adapter saves)."
        ),
    )
    p.add_argument(
        "--smoke",
        action="store_true",
        help=(
            "Smoke mode: tiny per-source slice (5 train rows + 2 eval probes), "
            "skip Haiku judge, write a stub run_result.json suitable for the "
            "downstream predictor_comparison.json builder smoke."
        ),
    )
    p.add_argument(
        "--training-rows",
        type=Path,
        default=DATA_DIR / "refusal_200_training.jsonl",
        help="Path to the 200-row refusal training pool.",
    )
    p.add_argument(
        "--eval-probes",
        type=Path,
        default=DATA_DIR / "refusal_50.jsonl",
        help="Path to the 50-prompt held-out refusal eval pool.",
    )
    args = p.parse_args()
    logging.basicConfig(
        level=os.environ.get("EPS_LOG_LEVEL", "INFO"),
        format="%(asctime)s %(levelname)s | %(message)s",
        stream=sys.stdout,
    )
    if args.only_source:
        args.sources = [args.only_source]

    OUT_ROOT.mkdir(parents=True, exist_ok=True)
    DATA_DIR.mkdir(parents=True, exist_ok=True)

    if args.smoke:
        return _smoke_main(args)
    return _production_main(args)


def _smoke_main(args: argparse.Namespace) -> int:
    """Smoke validation: tiny stub run_result per source, no GPU work."""
    runs_root = OUT_ROOT / "runs"
    runs_root.mkdir(parents=True, exist_ok=True)
    for source in args.sources:
        run_dir = runs_root / f"{source}_seed{args.seed}"
        run_dir.mkdir(parents=True, exist_ok=True)
        # The 23-bystander panel = the 23 other #411 personas. For the smoke,
        # we emit a stub trained_rate / base_rate / delta per (source,
        # bystander) cell so the downstream predictor_comparison.json builder
        # can assemble its 23-row substrate without a real adapter / judge.
        # In production this comes from the actual on-policy eval.
        bystanders = [s for s in SOURCES if s != source][:2]  # 2 for smoke
        per_cell = []
        for bys in bystanders:
            # Stub values -- numerically distinct so the smoke aggregator
            # sees real variance + non-zero Δ.
            trained_rate = 0.75 if bys == "comedian" else 0.30
            base_rate = 0.20
            per_cell.append(
                {
                    "source": source,
                    "bystander": bys,
                    "trained_rate": trained_rate,
                    "base_rate": base_rate,
                    "delta": trained_rate - base_rate,
                    "n_rollouts": 2,  # smoke
                    "n_probes": 2,
                    "judge_model": "smoke-stub",
                }
            )
        result = {
            "schema_version": 1,
            "experiment": "issue_518_refusal_smoke",
            "arm": "refusal",
            "source": source,
            "seed": args.seed,
            "smoke": True,
            "train_base_model": "Qwen/Qwen2.5-7B-Instruct",
            "training_rows_path": str(args.training_rows),
            "eval_probes_path": str(args.eval_probes),
            "per_cell": per_cell,
            "git_sha": _git_sha(),
            "timestamp_utc": datetime.now(UTC).isoformat(),
            "python": platform.python_version(),
        }
        (run_dir / "run_result.json").write_text(json.dumps(result, indent=2))
        print(f"SMOKE wrote {run_dir / 'run_result.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
