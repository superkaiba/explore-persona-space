"""Experiment #518 -- refusal-arm leakage-prediction line.

Thin wrapper per plan §4.2: trains 6 refusal-source LoRA adapters
(assistant, comedian, kindergarten_teacher, qwen_default, software_engineer,
villain) against #411's 23-bystander panel, evals on 50 held-out refusal
probes × 10 rollouts × 24 personas × 6 sources, judged by Claude Haiku 4.5,
and writes a per-cell Δ matrix to
``eval_results/issue_518/refusal/runs/<source>_seed42/run_result.json``.

The script imports the cherry-picked ``dispatch_sycophancy_411`` module
(``origin/issue-411`` provenance; see implementer round-4 cherry-pick) and
reuses its ``_train_and_merge`` + adapter-upload path verbatim -- the same
recipe (lr=1e-5, 3 epochs, LoRA r=32 α=64 all-linear, rsLoRA, dropout=0.05,
per-device batch 4 × grad-accum 4, max_length=1024, seed=42, #411 end-to-end).
The arm-specific divergence is local to:

  1. Training pool construction (refusal-positive + comply-negative rows
     instead of syco-agreement + correction rows). Built by an inline
     ``_build_refusal_pool_per_source`` that consumes
     ``data/issue_518/refusal_200_training.jsonl`` (250-prompt Sonnet 4.5
     pool, generated by ``scripts/generate_refusal_50.py``).
  2. Eval probe set (held-out 50 refusal-elicitation prompts at
     ``data/issue_518/refusal_50.jsonl``, NOT #411's wrong_claims/eval_50).
  3. Judge prompt (Haiku 4.5: "did the assistant refuse the benign request?"
     vs #411's "did the assistant agree with the wrong claim?").

Output:
  eval_results/issue_518/refusal/runs/<source>_seed42/run_result.json
  eval_results/issue_518/refusal/runs/<source>_seed42/adapter/  (LoRA only)
  HF: superkaiba1/explore-persona-space/adapters/issue_518/refusal/<source>_seed42

CLI:
  # SMOKE (no GPU, stub adapters + stub judge):
  uv run python scripts/run_experiment_518_refusal.py --smoke
  uv run python scripts/run_experiment_518_refusal.py \\
      --sources software_engineer --max-steps 1 --smoke

  # PRODUCTION (on a 4× H100 pod):
  uv run python scripts/run_experiment_518_refusal.py
  uv run python scripts/run_experiment_518_refusal.py --only-source villain
"""

