# Doc loading
# ────────────────────────────────────────────────────────────────────────────


def _load_jsonl(path: str | Path) -> list[dict]:
    """Stream a JSONL file into a list of dicts. No header, one object per line."""
    docs: list[dict] = []
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            docs.append(json.loads(line))
    return docs


def load_candidate_docs(
    fineweb_path: str | Path,
    lmsys_path: str | Path,
) -> list[dict]:
    """Load the 1200-doc extreme-bucket candidate set, tagging each doc with its
    source corpus + axis bucket. Returns a flat list with extra keys
    ``source_corpus`` ∈ {"fineweb", "lmsys"} and ``axis_bucket`` ∈
    {"top200", "bot200", "rand200"}.
    """
    out: list[dict] = []
    for path, corpus in ((fineweb_path, "fineweb"), (lmsys_path, "lmsys")):
        for doc in _load_jsonl(path):
            tail = str(doc.get("tail_group", "")).lower()
            bucket = TAIL_GROUP_TO_BUCKET.get(tail, "unknown")
            doc = dict(doc)
            doc["source_corpus"] = corpus
            doc["axis_bucket"] = bucket
            out.append(doc)
    log.info("loaded %d candidate docs (%s + %s)", len(out), fineweb_path, lmsys_path)
    return out


def random_bucket_subset(docs: Sequence[dict]) -> list[dict]:
    """Return the ``rand200`` subset of ``docs`` (typically ~400 docs across
    fineweb + lmsys) — used as the unbiased pool for the P1 sensitivity cell.
    """
    return [d for d in docs if d.get("axis_bucket") == "rand200"]


# ────────────────────────────────────────────────────────────────────────────
# Last-token activations on the BASE model under (assistant, doc-as-user)
# ────────────────────────────────────────────────────────────────────────────


def score_docs_against_directions(
    docs: Sequence[dict],
    directions: dict[str, torch.Tensor],
    base_model: str = "Qwen/Qwen2.5-7B-Instruct",
    layer: int = 20,
    device: str = "cuda:0",
    doc_activation_max_chars: int = 2000,
    dtype: torch.dtype = torch.bfloat16,
) -> torch.Tensor:
    """Score every doc against every persona direction at ``layer``.

    Activation recipe matches plan §4.4 step 1: the doc text is the
    user turn under the helpful-assistant system prompt, take last-token
    activation at ``layer``, then ``score[doc, persona] = cos(act, v_P)``.

    Args:
        docs: candidate docs (each must carry ``full_text``).
        directions: ``{persona: unit-norm Tensor(hidden_dim)}``.
        base_model: HF Hub id of the base model.
        layer: layer index to hook.
        device: cuda device.
        doc_activation_max_chars: cap on doc text fed to the model (so the
            chat-template fits inside the model's context window).
        dtype: model dtype.

    Returns:
        ``Tensor(n_docs, n_personas)`` of signed cosines, persona ordering
        matches ``sorted(directions.keys())``. Caller can index by persona name.
    """
    persona_names = sorted(directions.keys())
    direction_matrix = torch.stack([directions[p] for p in persona_names]).to(
        device=device, dtype=torch.float32
    )

    log.info(
        "scoring %d docs against %d persona directions at L%d (%s)",
        len(docs),
        len(persona_names),
        layer,
        base_model,
    )

    tokenizer = AutoTokenizer.from_pretrained(
        base_model, trust_remote_code=True, token=os.environ.get("HF_TOKEN")
    )
    model = AutoModelForCausalLM.from_pretrained(
        base_model,
        torch_dtype=dtype,
        device_map={"": device},
        trust_remote_code=True,
        token=os.environ.get("HF_TOKEN"),
    )
    model.eval()

    captured: dict[str, torch.Tensor] = {}

    def make_hook():
        def hook_fn(module, _input, output):
            hs = output[0] if isinstance(output, tuple) else output
            captured["hs"] = hs.detach()

        return hook_fn

    hook_handle = model.model.layers[layer].register_forward_hook(make_hook())

    try:
        scores = torch.zeros(len(docs), len(persona_names), dtype=torch.float32)
        for i, doc in enumerate(docs):
            text = (doc.get("full_text") or "")[:doc_activation_max_chars]
            if not text.strip():
                # zero-row → will never be picked as top-K (cos == 0 against unit vectors)
                continue
            messages = [
                {"role": "system", "content": "You are a helpful assistant."},
                {"role": "user", "content": text},
            ]
            rendered = tokenizer.apply_chat_template(
                messages, tokenize=False, add_generation_prompt=True
            )
            inputs = tokenizer(rendered, return_tensors="pt", padding=False).to(device)

            with torch.no_grad():
                _ = model(**inputs)

            hs = captured["hs"]  # (1, seq_len, hidden_dim)
            # Last token position (pad-aware)
            if tokenizer.pad_token_id is not None:
                mask = inputs["input_ids"][0] != tokenizer.pad_token_id
                last_pos = int(mask.nonzero()[-1].item())
            else:
                last_pos = hs.shape[1] - 1
            act = hs[0, last_pos, :].to(torch.float32)  # (hidden_dim,)
            act_norm = act.norm()
            if act_norm < 1e-8:
                continue
            act_unit = act / act_norm  # cos with unit direction == dot
            # cosine vs each persona-direction (directions are unit norm)
            cosines = torch.matmul(direction_matrix, act_unit.to(direction_matrix.device))
            scores[i] = cosines.cpu()

            if (i + 1) % 50 == 0:
                log.info("  scored %d/%d docs", i + 1, len(docs))
    finally:
        hook_handle.remove()
        del model
        gc.collect()
        torch.cuda.empty_cache()

    return scores


# ────────────────────────────────────────────────────────────────────────────
# Pool selection
# ────────────────────────────────────────────────────────────────────────────


def select_top_k_per_persona(
    docs: Sequence[dict],
    scores: torch.Tensor,
    persona_names: Sequence[str],
    k: int = 50,
) -> dict[str, list[tuple[int, float]]]:
    """For each persona, return the top-K (doc_index, cos) pairs.

    The cosine is the signed value — we want the docs that score MOST
    positively against the persona direction (i.e., are most persona-like).
    """
    out: dict[str, list[tuple[int, float]]] = {}
    persona_names = list(persona_names)
    for j, p in enumerate(persona_names):
        col = scores[:, j]
        # Argsort descending. NB: tied scores resolve in stable insertion order
        # (torch.argsort is stable from 2.x onward), so this is deterministic.
        order = torch.argsort(col, descending=True)
        picks: list[tuple[int, float]] = []
        for idx in order.tolist():
            cos = float(col[idx].item())
            if cos <= 0.0:
                # No persona-positive docs left; stop early.
                # Persona-style pool selection requires positive cosines —
                # otherwise the docs are anti-persona, the opposite of the intent.
                break
            picks.append((idx, cos))
            if len(picks) >= k:
                break
        if len(picks) < k:
            log.warning(
                "select_top_k_per_persona: persona=%s only %d/%d docs have positive cos; "
                "consider widening the candidate pool or recomputing persona directions",
                p,
                len(picks),
                k,
            )
        out[p] = picks
    return out


def select_neutral_per_persona(
    docs: Sequence[dict],
    scores: torch.Tensor,
    persona_names: Sequence[str],
    k: int = 50,
    threshold: float = 0.05,
    threshold_step: float = 0.01,
    threshold_max: float = 0.30,
) -> tuple[dict[str, list[tuple[int, float]]], dict[str, float]]:
    """For each persona, pick K docs with the smallest absolute cosine
    (``|cos| < threshold``). If fewer than K qualify, widen the threshold by
    ``threshold_step`` until ≥ K docs qualify or ``threshold_max`` is hit.

    Returns the per-persona selections AND the achieved threshold per persona.
    """
    out: dict[str, list[tuple[int, float]]] = {}
    achieved: dict[str, float] = {}
    persona_names = list(persona_names)
    for j, p in enumerate(persona_names):
        col = scores[:, j]
        thr = threshold
        picks: list[tuple[int, float]] = []
        while thr <= threshold_max + 1e-9:
            picks = []
            for idx in range(col.shape[0]):
                cos = float(col[idx].item())
                if abs(cos) < thr:
                    picks.append((idx, cos))
            if len(picks) >= k:
                # Sort by |cos| ascending so the most-neutral docs come first
                picks.sort(key=lambda t: abs(t[1]))
                picks = picks[:k]
                achieved[p] = thr
                break
            thr += threshold_step
        else:
            log.error(
                "select_neutral_per_persona: persona=%s could not reach k=%d docs even at "
                "|cos|<%.3f; got %d. Returning what we have; flag in pool meta.",
                p,
                k,
                threshold_max,
                len(picks),
            )
            achieved[p] = threshold_max
            picks.sort(key=lambda t: abs(t[1]))
            picks = picks[:k]
        out[p] = picks
    return out, achieved


# ────────────────────────────────────────────────────────────────────────────
# Assistant-turn generation (vLLM)
# ────────────────────────────────────────────────────────────────────────────


def _build_chat_for_generation(system_prompt: str, user_text: str) -> list[dict]:
    return [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_text},
    ]


def generate_assistant_turns(
    llm,  # vllm.LLM
    tokenizer,
    user_texts: Sequence[str],
    system_prompt: str,
    temperature: float = 0.7,
    max_tokens: int = 512,
    seed: int = 42,
) -> list[str]:
    """Run vLLM batched generation to produce one assistant turn per ``user_text``.

    The few-shot example pool's "persona-style assistant turn" is the base
    model's response to the doc under the persona system prompt — this matches
    v3's ``generate_convergence_data`` recipe (plan §4.4 step 5).

    We accept a pre-constructed ``llm`` to amortize model load across pools.
    """
    from vllm import SamplingParams  # local import to keep module light at test time

    sampling = SamplingParams(
        n=1, temperature=temperature, top_p=1.0, max_tokens=max_tokens, seed=seed
    )
    prompts = []
    for ut in user_texts:
        msgs = _build_chat_for_generation(system_prompt, ut)
        prompts.append(
            tokenizer.apply_chat_template(msgs, tokenize=False, add_generation_prompt=True)
        )
    outputs = llm.generate(prompts, sampling)
    # vLLM returns one RequestOutput per prompt, with one CompletionOutput in .outputs[0]
    return [out.outputs[0].text for out in outputs]


# ────────────────────────────────────────────────────────────────────────────
# ZLT contamination filter (plan §4.4 step 5b stage (a))
# ────────────────────────────────────────────────────────────────────────────


def is_contaminated(example: Example | dict) -> bool:
    """True iff ``[zlt]`` appears (case-insensitively) in EITHER the user-doc
    text OR the generated assistant turn."""
    user_text = example.user if isinstance(example, Example) else example.get("user", "")
    asst_text = example.assistant if isinstance(example, Example) else example.get("assistant", "")
    return ZLT_LOWER in user_text.lower() or ZLT_LOWER in asst_text.lower()


def filter_zlt_contamination(
    examples: list[Example],
    persona: str,
    pool_kind: str,
    hard_gate: float = 0.10,
) -> tuple[list[Example], int, float]:
    """Drop contaminated examples; fail loudly if drop rate exceeds ``hard_gate``.

    Returns ``(kept_examples, n_dropped, drop_rate)``.

    Raises:
        RuntimeError: when ``drop_rate > hard_gate``. Caller must NOT swallow.
    """
    if not examples:
        return [], 0, 0.0
    kept: list[Example] = []
    dropped = 0
    for ex in examples:
        if is_contaminated(ex):
            dropped += 1
            log.warning(
                "ZLT contamination: dropping example persona=%s pool=%s doc_id=%s",
                persona,
                pool_kind,
                ex.doc_id,
            )
            continue
        kept.append(ex)
    n_total = len(examples)
    drop_rate = dropped / n_total
    if drop_rate > hard_gate:
        raise RuntimeError(
            f"Pool contamination drop rate {drop_rate:.1%} exceeds {hard_gate:.0%} "
            f"threshold for persona={persona!r} pool={pool_kind!r}. "
            f"Investigate: does the base model emit [ZLT] under this persona's prompt? "
            f"Drop counts: {dropped}/{n_total}. Aborting before eval to prevent silent confound."
        )
    return kept, dropped, drop_rate


