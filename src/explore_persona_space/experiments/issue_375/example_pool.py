def save_pool_jsonl(
    examples: list[Example],
    path: str | Path,
) -> None:
    """Save a list of examples to a JSONL file."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as f:
        for ex in examples:
            f.write(json.dumps(ex.to_dict(), ensure_ascii=False) + "\n")
    log.info("saved %d examples to %s", len(examples), path)


def load_pool_jsonl(path: str | Path) -> list[Example]:
    """Inverse of :func:`save_pool_jsonl`."""
    out: list[Example] = []
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            d = json.loads(line)
            out.append(
                Example(
                    persona=d["persona"],
                    doc_id=int(d["doc_id"]),
                    user=d["user"],
                    assistant=d["assistant"],
                    cos_to_persona_dir=float(d["cos_to_persona_dir"]),
                    source_corpus=d.get("source_corpus", "unknown"),
                    qwen3_axis_bucket=d.get("qwen3_axis_bucket", "unknown"),
                )
            )
    return out


def write_pool_meta(
    meta: dict[str, dict],
    path: str | Path,
) -> None:
    """Serialize the per-persona pool-construction metadata to JSON."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as f:
        json.dump(meta, f, indent=2, ensure_ascii=False)
    log.info("saved pool meta to %s", path)


# ────────────────────────────────────────────────────────────────────────────
# Builder helpers (high-level)
# ────────────────────────────────────────────────────────────────────────────


def _top5_docs_meta(
    picks: Iterable[tuple[int, float]],
    docs: Sequence[dict],
) -> list[dict]:
    """For pool meta: first-5 (doc_id, source, snippet, axis_bucket, cos)."""
    out: list[dict] = []
    for idx, cos in list(picks)[:5]:
        d = docs[idx]
        out.append(
            {
                "doc_id": int(d.get("doc_id", idx)),
                "source": d.get("source_corpus", "unknown"),
                "axis_bucket": d.get("axis_bucket", "unknown"),
                "cos_to_persona_dir": float(cos),
                "snippet_first_200_chars": (d.get("full_text") or "")[:200],
            }
        )
    return out


def _bucket_distribution(
    picks: Iterable[tuple[int, float]],
    docs: Sequence[dict],
) -> dict[str, int]:
    counts: dict[str, int] = {}
    for idx, _ in picks:
        bucket = docs[idx].get("axis_bucket", "unknown")
        counts[bucket] = counts.get(bucket, 0) + 1
    return counts


def _corpus_counts(
    picks: Iterable[tuple[int, float]],
    docs: Sequence[dict],
) -> tuple[int, int]:
    fineweb = sum(1 for idx, _ in picks if docs[idx].get("source_corpus") == "fineweb")
    lmsys = sum(1 for idx, _ in picks if docs[idx].get("source_corpus") == "lmsys")
    return fineweb, lmsys


def build_pool_meta(
    persona: str,
    pool_kind: str,
    picks: list[tuple[int, float]],
    docs: Sequence[dict],
    n_dropped_zlt: int,
    drop_rate: float,
    achieved_neutral_threshold: float | None = None,
) -> dict:
    """Assemble one persona's pool-meta entry — see plan §4.4 step 6."""
    fineweb, lmsys = _corpus_counts(picks, docs)
    n_kept_before_drop = len(picks)
    return {
        "pool_kind": pool_kind,
        "n_selected_before_drop": n_kept_before_drop,
        "n_kept_after_drop": n_kept_before_drop - n_dropped_zlt,
        "contamination_drop_count": int(n_dropped_zlt),
        "contamination_drop_rate": float(drop_rate),
        "achieved_neutral_threshold": achieved_neutral_threshold,
        "fineweb_count": int(fineweb),
        "lmsys_count": int(lmsys),
        "fineweb_lmsys_split": [
            float(fineweb / n_kept_before_drop) if n_kept_before_drop else 0.0,
            float(lmsys / n_kept_before_drop) if n_kept_before_drop else 0.0,
        ],
        "qwen3_axis_bucket_distribution": _bucket_distribution(picks, docs),
        "top5_docs": _top5_docs_meta(picks, docs),
    }
