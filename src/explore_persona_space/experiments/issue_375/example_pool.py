"""Example-pool construction for issue #375.

Builds the three few-shot example pools described in plan §4.4:

1. **Persona-style** — for each source persona P, the top-K docs by
   cos(L20 doc-activation, v_P) from the FULL 1200-doc extreme-bucket set.
   Each doc's user-turn is paired with an assistant turn generated by the
   *base* model under P's system prompt at T=0.7.

2. **Neutral** — for each P, K docs with ``|cos| < 0.05`` (widen by 0.01
   if fewer than K qualify; logged). Assistant turn is generated under the
   helpful-assistant system prompt, no persona styling.

3. **Persona-style random-bucket** — for villain only, top-K docs by
   cos(...) from the 400-doc *random-bucket* subset (the union of the
   ``rand-200`` partitions from both JSONLs). Used by the P1 sensitivity
   cell (§4.4 step 3b).

Hard gates (plan §4.4 step 5b):

- Pool-build-time ZLT contamination filter — drop any example whose
  generated assistant turn (or the source doc text) contains ``[zlt]``
  case-insensitively. Drop rate > 10% per persona ⇒ RuntimeError.
- The eval-time prompt scan + audit-trail dump live in
  :mod:`drift_eval`.
"""

from __future__ import annotations

import gc
import json
import logging
import os
from collections.abc import Iterable, Sequence
from dataclasses import dataclass, field
from pathlib import Path

import torch
from transformers import AutoModelForCausalLM, AutoTokenizer

log = logging.getLogger(__name__)

# Tag we look for case-insensitively at every gate.
ZLT_LOWER = "[zlt]"

# Tail-group → "axis bucket" name used in example_pool_meta.json. The cached
# JSONLs use ``tail_group`` ∈ {top, bot, rand}; we re-label as the bucket
# name the plan §4.4 step 3b uses.
TAIL_GROUP_TO_BUCKET = {"top": "top200", "bot": "bot200", "rand": "rand200"}


@dataclass
class Example:
    """A single few-shot example (one user turn + one assistant turn)."""

    persona: str  # persona under which the assistant turn was generated; "assistant" for neutral
    doc_id: int
    user: str
    assistant: str
    cos_to_persona_dir: float  # signed cosine; assistant-turn target persona for matching cells
    source_corpus: str  # "fineweb" or "lmsys"
    qwen3_axis_bucket: str  # "top200" / "bot200" / "rand200"

    def to_dict(self) -> dict:
        return {
            "persona": self.persona,
            "doc_id": self.doc_id,
            "user": self.user,
            "assistant": self.assistant,
            "cos_to_persona_dir": float(self.cos_to_persona_dir),
            "source_corpus": self.source_corpus,
            "qwen3_axis_bucket": self.qwen3_axis_bucket,
        }


@dataclass
class PoolBuildReport:
    """Diagnostics from one pool-construction run (per persona)."""

    persona: str
    pool_kind: str  # "persona-style" / "neutral" / "persona-style-random-bucket"
    n_kept: int
    n_dropped_zlt: int
    drop_rate: float
    achieved_neutral_threshold: float | None = None  # only for neutral pools
    top5_docs: list[dict] = field(default_factory=list)
    fineweb_count: int = 0
    lmsys_count: int = 0
    bucket_distribution: dict[str, int] = field(default_factory=dict)


