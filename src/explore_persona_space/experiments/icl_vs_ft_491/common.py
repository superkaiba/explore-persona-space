def _load_persona_keyed(filename: str, expected: int) -> dict[tuple[str, str], dict]:
    comp = _load_completions(HF_PREFIX_471, filename, subdir="i471")
    out: dict[tuple[str, str], dict] = {}
    for k, v in comp.items():
        if "::" not in k:
            raise AssertionError(f"{filename}: key {k!r} missing '::' delimiter — schema drift")
        persona, q = k.split("::", 1)
        out[(persona, q)] = v
    if len(out) != expected:
        raise AssertionError(f"{filename}: expected {expected} completions, got {len(out)}")
    return out


