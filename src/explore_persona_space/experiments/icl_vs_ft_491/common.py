def panel_system_prompts() -> dict[str, str | None]:
    """Return {context_id: system_prompt_or_None} for the 10-context panel.

    ``no_system`` maps to None — the Qwen-2.5 chat template injects its own
    default system turn when no system message is supplied, which is exactly
    the context ``R_no_system_qtest.json`` was generated under.
    """
    from explore_persona_space.experiments.factor_screen_365.persona_panel import (
        EVAL_PERSONAS_24,
    )

    prompts: dict[str, str | None] = {
        "villain": VILLAIN_SYSTEM_PROMPT,
        "helpful": HELPFUL_SYSTEM_PROMPT,
        "no_system": None,
    }
    for pid in PANEL_CONTEXT_IDS:
        if pid in prompts:
            continue
        if pid not in EVAL_PERSONAS_24:
            raise AssertionError(
                f"panel persona {pid!r} missing from EVAL_PERSONAS_24 — persona_panel.py drifted"
            )
        prompts[pid] = EVAL_PERSONAS_24[pid]
    assert prompts["villain"] == VILLAIN_SYSTEM_PROMPT
    return prompts


# ── Marker tokenization assert (in-process, every entrypoint) ────────────


def assert_marker_tokenization(tokenizer) -> None:
    """Fail loud unless the marker + EOS tokenize to the pinned single ids."""
    ids = tokenizer.encode(MARKER_TEXT, add_special_tokens=False)
    if ids != [MARKER_ID]:
        raise AssertionError(
            f"Marker {MARKER_TEXT!r} tokenizes to {ids}, expected [{MARKER_ID}]. "
            "Wrong tokenizer / marker drift — refusing to run (incident #537)."
        )
    eos = tokenizer.convert_tokens_to_ids(EOS_TOKEN)
    if eos != EOS_ID:
        raise AssertionError(f"{EOS_TOKEN!r} id={eos}, expected {EOS_ID}.")


def load_tokenizer():
    """Load the pinned-revision tokenizer and run the marker assert."""
    from transformers import AutoTokenizer

    tok = AutoTokenizer.from_pretrained(
        BASE_MODEL, revision=BASE_MODEL_REVISION, trust_remote_code=True
    )
    assert_marker_tokenization(tok)
    return tok


# ── Frozen-artifact loaders (HF fallback, fail-loud) ─────────────────────


def _hf_pull(prefix: str, filename: str, local: Path) -> None:
    """Pull one frozen artifact from the HF data repo into ``local``."""
    import shutil

    from huggingface_hub import hf_hub_download

    logger.info("Pulling %s/%s from HF data repo %s ...", prefix, filename, HF_DATA_REPO)
    local.parent.mkdir(parents=True, exist_ok=True)
    downloaded = hf_hub_download(
        repo_id=HF_DATA_REPO,
        repo_type="dataset",
        filename=f"{prefix}/{filename}",
        revision="main",
    )
    shutil.copyfile(downloaded, local)
    if not local.exists() or local.stat().st_size == 0:
        raise RuntimeError(
            f"HF download of {prefix}/{filename} claimed success but {local} is empty/missing."
        )


def _load_frozen_json(prefix: str, filename: str, *, subdir: str) -> dict:
    """Load a frozen JSON artifact, pulling from HF when not cached locally."""
    local = DATA_DIR / "frozen" / subdir / filename
    if not local.exists():
        _hf_pull(prefix, filename, local)
    return json.loads(local.read_text())


def load_q_demo() -> list[str]:
    """The frozen 50 demo questions (#465), with content-hash verification."""
    import hashlib

    payload = _load_frozen_json(HF_PREFIX_465, "q_demo.json", subdir="i465")
    qs = payload["questions"]
    if len(qs) != 50:
        raise AssertionError(f"q_demo.json: expected 50 questions, got {len(qs)}")
    recorded = payload.get("content_hash")
    actual = hashlib.sha256(
        json.dumps(qs, sort_keys=False, ensure_ascii=False).encode("utf-8")
    ).hexdigest()
    if recorded and recorded != actual:
        raise RuntimeError(
            f"q_demo.json content_hash MISMATCH: recorded {recorded[:12]}..., "
            f"computed {actual[:12]}... — artifact corrupted; refusing to load."
        )
    return qs


