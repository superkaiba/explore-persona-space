def load_panel_substrates() -> dict[str, dict[str, str]]:
    """Return {context_id: {q: response_text}} for the full 10-context panel.

    Asserts every Q_test question is covered for every context — a silent
    substrate hole would shrink the per-context mean's denominator.
    """
    q_test = load_q_test()
    out: dict[str, dict[str, str]] = {}
    r_villain = load_r_villain()
    out["villain"] = {q: r_villain[q]["response_text"] for q in q_test}
    out["helpful"] = {q: v["response_text"] for q, v in load_r_helpful_qtest().items()}
    out["no_system"] = {q: v["response_text"] for q, v in load_r_no_system_qtest().items()}
    trained_neg = load_r_trained_negatives_qtest()
    bystander = load_r_bystander_qtest()
    for pid in ("medical_doctor", "police_officer"):
        out[pid] = {q: v["response_text"] for (p, q), v in trained_neg.items() if p == pid}
    for pid in ("software_engineer", "kindergarten_teacher", "comedian", "hero", "lawyer"):
        out[pid] = {q: v["response_text"] for (p, q), v in bystander.items() if p == pid}
    for cid in PANEL_CONTEXT_IDS:
        missing = [q for q in q_test if q not in out[cid]]
        if missing:
            raise AssertionError(
                f"substrate hole: context {cid!r} missing {len(missing)} Q_test "
                f"questions (first: {missing[0][:60]!r})"
            )
    return out


# ── Context rendering (the slot-read prefix) ─────────────────────────────


def render_messages(
    *,
    system_prompt: str | None,
    demo_turns: list[tuple[str, str]] | None,
    question: str,
) -> list[dict]:
    """Build the chat message list: [system?] + demo (user, assistant) pairs + probe user turn."""
    messages: list[dict] = []
    if system_prompt is not None:
        messages.append({"role": "system", "content": system_prompt})
    for dq, dr in demo_turns or []:
        messages.append({"role": "user", "content": dq})
        messages.append({"role": "assistant", "content": dr})
    messages.append({"role": "user", "content": question})
    return messages


def render_slot_context(
    tokenizer,
    *,
    system_prompt: str | None,
    demo_turns: list[tuple[str, str]] | None,
    question: str,
    response_text: str,
    max_length: int = 8192,
) -> str:
    """Render the teacher-forced slot-read prefix: chat scaffold + R (NO marker).

    The 4-float read scores the NEXT-token distribution at the last position
    of this string — the post-response slot where the marker would appear.
    Fails loud (never truncates) past ``max_length`` tokens (#260 rule).
    """
    messages = render_messages(
        system_prompt=system_prompt, demo_turns=demo_turns, question=question
    )
    prompt_text = tokenizer.apply_chat_template(
        messages, tokenize=False, add_generation_prompt=True
    )
    context = prompt_text + response_text
    n_tok = len(tokenizer.encode(context, add_special_tokens=False))
    if n_tok > max_length:
        raise ValueError(
            f"slot context tokenizes to {n_tok} > max_length={max_length} "
            f"(question[:50]={question[:50]!r}); refusing to truncate (#260)."
        )
    return context


