"""Data preparation for task #520 — question pool, R_persona cache, training mixes.

Pipeline (plan §4 step 4):

1. **Load the 20-question generic pool** from #311's
   ``eval_results/issue_311/arm1_completions_Aonly_paramedic_comedian.json``
   (the keys of any persona-dict are exactly the 20 questions). These are
   the same questions #311 / #456 used.

2. **Load the 20-response-per-question per-persona base-model R cache** from
   the same JSON. The plan calls these ``R_persona(q)``: greedy / sampled
   base-model responses under each persona's own system prompt. The cache
   gives us 400 ``(question, R_persona(q))`` pairs per persona, which is
   the load-bearing budget the plan inherits from #311.

3. **Build training mixes per arm** (positives + 4-persona negatives, beta-1
   or beta-2 ratio).

Beta-1 (singletons 1:2, joint 1:1):
- Singleton A: 400 positives (paramedic + ※) + 800 negatives (200 each of
  the 4 neg personas). Ratio 1:2.
- Singleton B: same shape, with persona B.
- Joint A+B: 400 positives (A) + 400 positives (B) + 800 negatives. Ratio 1:1.

Beta-2 (strict 1:1 across all arms):
- Singleton A: 400 positives + 400 negatives (100 each). Ratio 1:1.
- Singleton B: same.
- Joint A+B: 800 positives + 800 negatives (200 each). Ratio 1:1.
"""

from __future__ import annotations

import json
import logging
import os
import random
from collections.abc import Iterable
from dataclasses import dataclass
from pathlib import Path

from explore_persona_space.experiments.issue520.persona_panel import (
    MARKER_TEXT,
    NEGATIVE_PERSONAS,
    get_system_prompt,
)

logger = logging.getLogger(__name__)


@dataclass(frozen=True)
class RPool:
    """A per-persona base-model R cache.

    ``responses[persona][question]`` is a list of base-model greedy/sampled
    responses for that (persona, question) pair. With #311's 20 questions x
    20 responses each, ``len(responses[persona])==20`` and each list has 20
    entries, giving 400 (q, R) pairs per persona.
    """

    questions: list[str]  # length 20 (the canonical #311 pool)
    responses: dict[str, dict[str, list[str]]]  # persona -> q -> [R, ...]
    source_path: str
    source_sha256: str
    # When True, the responses came from the #311 ``arm1_completions_*`` JSONs
    # which were generated by TRAINED adapters (21% contain a stray ``[ZLT]``).
    # The pair builder strips ``[ZLT]`` substrings on read; flag is purely
    # informational for downstream reporting + the smoke vs full-run choice.
    contaminated_with_zlt: bool = False

    def pairs_for_persona(self, persona: str) -> list[tuple[str, str]]:
        """Return all (question, R) pairs for ``persona`` (sorted deterministically).

        With #311's pool this is 400 pairs (20 questions x 20 responses). The
        order is (question_index, response_index) lexicographic so two
        invocations on the same pool give byte-identical row sequences.

        When the pool is ``contaminated_with_zlt`` (the #311 arm1 case), any
        ``[ZLT]`` substring is stripped from each response so the resulting
        positive row's marker land cleanly at the *end* (no stray markers
        embedded mid-response that the collator would also mask).
        """
        if persona not in self.responses:
            raise KeyError(
                f"Persona {persona!r} not in R cache; available: {sorted(self.responses)}"
            )
        pairs: list[tuple[str, str]] = []
        for q in self.questions:
            if q not in self.responses[persona]:
                continue
            for r in self.responses[persona][q]:
                if self.contaminated_with_zlt and "[ZLT]" in r:
                    r = r.replace("[ZLT]", "").rstrip()
                pairs.append((q, r))
        return pairs

    def num_pairs(self, persona: str) -> int:
        return len(self.pairs_for_persona(persona))


def _sha256_file(path: Path) -> str:
    import hashlib

    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()[:16]


# Default search paths for the #311 R cache. The first one to exist wins.
# These are checked at preflight time and recorded in the chosen-source file
# /tmp/issue_520_question_pool_source.txt so the dispatcher reads from the
# same location.
_R_CACHE_CANDIDATE_PATHS: tuple[str, ...] = (
    # On the local repo / worktree (where #311's eval_results lives by default)
    "eval_results/issue_311/arm1_completions_Aonly_paramedic_comedian.json",
)


def load_r_cache(path: str | Path | None = None) -> RPool:
    """Load the per-persona R cache from #311's arm1 raw completions JSON.

    If ``path`` is None, search the default candidate paths in order and use
    the first one that exists.

    The JSON shape is ``{persona: {question: [R1, R2, ...]}}`` — see
    ``eval_results/issue_311/arm1_completions_Aonly_paramedic_comedian.json``
    in the repo.

    Raises ``FileNotFoundError`` (fail loud) if no candidate resolves.
    """
    if path is None:
        for cand in _R_CACHE_CANDIDATE_PATHS:
            if Path(cand).exists():
                path = cand
                break
        else:
            raise FileNotFoundError(
                "No R cache resolved from candidates: "
                + ", ".join(_R_CACHE_CANDIDATE_PATHS)
                + ". Set EPM_ISSUE520_R_CACHE or pass --r-cache to override."
            )
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(f"R cache path does not exist: {path}")

    with open(path) as f:
        data = json.load(f)
    if not isinstance(data, dict) or not data:
        raise RuntimeError(f"R cache JSON malformed at {path}: not a non-empty dict")

    # Use the first persona's question keys as the canonical pool.
    first_persona = next(iter(data))
    questions = list(data[first_persona].keys())
    if not questions:
        raise RuntimeError(f"R cache has no questions under persona {first_persona!r}")

    # Sanity: every persona must have the same question keys.
    for p, qd in data.items():
        if set(qd.keys()) != set(questions):
            missing = set(questions) - set(qd.keys())
            extra = set(qd.keys()) - set(questions)
            raise RuntimeError(
                f"R cache shape MISMATCH: persona {p!r} has missing={missing} "
                f"extra={extra} vs canonical pool"
            )

    # The #311 arm1_completions_* JSONs were generated by TRAINED adapters
    # (Aonly = paramedic-implant adapter). ~21% of the responses contain a
    # stray ``[ZLT]`` from the trained-marker leak; we strip those at
    # pair-read time. The cleaner approach for a full run is to regenerate
    # R_persona(q) from the BASE model on the pod (see ``gen_r_persona.py``).
    contaminated = "arm1_completions" in str(path)

    return RPool(
        questions=questions,
        responses=data,
        source_path=str(path),
        source_sha256=_sha256_file(path),
        contaminated_with_zlt=contaminated,
    )


# ── Row building ────────────────────────────────────────────────────────────


def make_prompt_completion(
    system_prompt: str,
    user_question: str,
    assistant_answer: str,
) -> dict:
    """Build a single SFT JSONL row (Qwen-2.5 chat format, prompt-completion).

    Matches what ``train_lora()`` expects: ``{prompt: [system,user],
    completion: [assistant]}``.
    """
    return {
        "prompt": [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_question},
        ],
        "completion": [{"role": "assistant", "content": assistant_answer}],
    }


def build_positive_rows(
    pool: RPool,
    source_persona: str,
    *,
    n_positives: int,
    rng: random.Random,
) -> list[dict]:
    """Build ``n_positives`` positive rows for ``source_persona``.

    Each row is ``(T_source(q), q, R_source(q) + " ※")`` where R is the
    base-model response cached in ``pool``. ``n_positives`` <= total pairs
    available; we shuffle pairs deterministically (via ``rng``) and take the
    first N.
    """
    pairs = pool.pairs_for_persona(source_persona)
    if n_positives > len(pairs):
        raise ValueError(
            f"Requested {n_positives} positives for {source_persona!r} but "
            f"only {len(pairs)} (q, R) pairs available in pool {pool.source_path}"
        )
    pairs = list(pairs)
    rng.shuffle(pairs)
    sys_prompt = get_system_prompt(source_persona)
    rows: list[dict] = []
    for q, r in pairs[:n_positives]:
        # POSITIVE: response + marker. MarkerOnlyDataCollator (tail_tokens=0)
        # masks the loss to the marker token + EOS only — R itself is
        # zero-gradient and stays on-policy.
        completion = r + MARKER_TEXT
        rows.append(make_prompt_completion(sys_prompt, q, completion))
    return rows


def build_negative_rows(
    pool: RPool,
    *,
    n_negatives_total: int,
    negatives: Iterable[str] = NEGATIVE_PERSONAS,
    rng: random.Random,
) -> list[dict]:
    """Build ``n_negatives_total`` negative rows, evenly across the 4 negative personas.

    Each negative row uses the SAME (q, R) cached pair under that negative
    persona's own system prompt. No marker. With
    ``suppress_at_post_response_slot=True`` on the collator, loss lands at the
    first ``<|im_end|>`` in the completion region — same slot the DV reads
    on positives — pushing log P(※) DOWN under softmax competition (per #474).
    """
    negs = list(negatives)
    if n_negatives_total % len(negs) != 0:
        raise ValueError(
            f"n_negatives_total={n_negatives_total} must be divisible by "
            f"number of negative personas ({len(negs)})"
        )
    per_neg = n_negatives_total // len(negs)
    rows: list[dict] = []
    for neg_persona in negs:
        pairs = pool.pairs_for_persona(neg_persona)
        if per_neg > len(pairs):
            raise ValueError(
                f"Requested {per_neg} negatives per persona but only "
                f"{len(pairs)} (q, R) pairs available for {neg_persona!r}"
            )
        pairs = list(pairs)
        rng.shuffle(pairs)
        sys_prompt = get_system_prompt(neg_persona)
        for q, r in pairs[:per_neg]:
            # NEGATIVE: no marker. Loss masked at the post-response slot
            # (the first <|im_end|>) by MarkerOnlyDataCollator when
            # suppress_at_post_response_slot=True is set on the train cfg.
            rows.append(make_prompt_completion(sys_prompt, q, r))
    return rows


# ── Arm specs (plan §4 condition table) ─────────────────────────────────────


@dataclass(frozen=True)
class ArmSpec:
    """Specification of one training arm (one cell in plan §4).

    The fields mirror the plan §4 condition-table columns plus the actual
    integer ratios used to construct the JSONL.
    """

    pair_name: str  # "far" or "near"
    arm: str  # "A_only", "B_only", "joint"
    ratio: str  # "b1" or "b2"
    source_a: str
    source_b: str  # same as source_a for "A_only"; same as source_b for "B_only"; both for "joint"
    n_pos_source_a: int  # number of positives drawn from source A
    n_pos_source_b: int  # number of positives drawn from source B
    n_neg_total: int  # total negatives (spread evenly across 4 negative personas)

    @property
    def slug(self) -> str:
        return f"{self.pair_name}_{self.arm}_{self.ratio}"

    @property
    def n_positives_total(self) -> int:
        return self.n_pos_source_a + self.n_pos_source_b

    def sources_used(self) -> list[str]:
        out = [self.source_a]
        if self.arm == "joint":
            out.append(self.source_b)
        return out


def build_arm_specs_for_pair(
    pair_name: str,
    source_a: str,
    source_b: str,
    *,
    n_positives_per_source: int = 400,
    include_b2: bool = False,
) -> list[ArmSpec]:
    """Build the 3 (or 6) arm specs for a pair under beta-1 (+ optional beta-2).

    Beta-1 (always): singleton 1:2, joint 1:1.
    - A_only: ``n_positives_per_source`` positives in A, 0 in B; 2N negatives.
    - B_only: 0 positives in A, ``n_positives_per_source`` positives in B; 2N negatives.
    - joint: N positives in A + N in B; 2N negatives (so positives:negatives = 1:1).

    Beta-2 (if include_b2): strict 1:1 across all arms.
    - A_only: N positives in A, 0 in B; N negatives.
    - B_only: 0 in A, N in B; N negatives.
    - joint: N in A + N in B; 2N negatives.
    """
    N = n_positives_per_source
    arms: list[ArmSpec] = []

    # Beta-1
    arms.append(
        ArmSpec(
            pair_name=pair_name,
            arm="A_only",
            ratio="b1",
            source_a=source_a,
            source_b=source_b,
            n_pos_source_a=N,
            n_pos_source_b=0,
            n_neg_total=2 * N,
        )
    )
    arms.append(
        ArmSpec(
            pair_name=pair_name,
            arm="B_only",
            ratio="b1",
            source_a=source_a,
            source_b=source_b,
            n_pos_source_a=0,
            n_pos_source_b=N,
            n_neg_total=2 * N,
        )
    )
    arms.append(
        ArmSpec(
            pair_name=pair_name,
            arm="joint",
            ratio="b1",
            source_a=source_a,
            source_b=source_b,
            n_pos_source_a=N,
            n_pos_source_b=N,
            n_neg_total=2 * N,
        )
    )

    if include_b2:
        arms.append(
            ArmSpec(
                pair_name=pair_name,
                arm="A_only",
                ratio="b2",
                source_a=source_a,
                source_b=source_b,
                n_pos_source_a=N,
                n_pos_source_b=0,
                n_neg_total=N,
            )
        )
        arms.append(
            ArmSpec(
                pair_name=pair_name,
                arm="B_only",
                ratio="b2",
                source_a=source_a,
                source_b=source_b,
                n_pos_source_a=0,
                n_pos_source_b=N,
                n_neg_total=N,
            )
        )
        arms.append(
            ArmSpec(
                pair_name=pair_name,
                arm="joint",
                ratio="b2",
                source_a=source_a,
                source_b=source_b,
                n_pos_source_a=N,
                n_pos_source_b=N,
                n_neg_total=2 * N,
            )
        )

    return arms


# ── Training-data JSONL builder ─────────────────────────────────────────────


def build_training_jsonl(
    pool: RPool,
    arm: ArmSpec,
    *,
    seed: int,
    out_path: Path,
    negatives: Iterable[str] = NEGATIVE_PERSONAS,
) -> dict:
    """Materialize the training JSONL for one arm-seed.

    Returns a metadata dict with row counts + the pool source hash.
    """
    rng = random.Random(seed * 13 + hash(arm.slug) % (1 << 16))

    rows: list[dict] = []
    if arm.n_pos_source_a > 0:
        rows.extend(
            build_positive_rows(pool, arm.source_a, n_positives=arm.n_pos_source_a, rng=rng)
        )
    if arm.n_pos_source_b > 0 and arm.source_b != arm.source_a:
        rows.extend(
            build_positive_rows(pool, arm.source_b, n_positives=arm.n_pos_source_b, rng=rng)
        )
    # Shuffle positives among themselves so the order of source-A vs source-B
    # positives in the joint arm doesn't cluster.
    rng.shuffle(rows)
    n_positives = len(rows)

    neg_rows = build_negative_rows(
        pool, n_negatives_total=arm.n_neg_total, negatives=negatives, rng=rng
    )
    rows.extend(neg_rows)
    # Full final shuffle.
    rng.shuffle(rows)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as f:
        for row in rows:
            f.write(json.dumps(row) + "\n")

    meta = {
        "arm_slug": arm.slug,
        "seed": seed,
        "n_total_rows": len(rows),
        "n_positives": n_positives,
        "n_negatives": len(neg_rows),
        "n_pos_source_a": arm.n_pos_source_a,
        "n_pos_source_b": arm.n_pos_source_b,
        "source_a": arm.source_a,
        "source_b": arm.source_b,
        "pair_name": arm.pair_name,
        "ratio": arm.ratio,
        "pool_source_path": pool.source_path,
        "pool_source_sha256": pool.source_sha256,
        "negatives": list(negatives),
        "out_path": str(out_path),
    }
    return meta


def assert_rows_fit_max_length(
    jsonl_path: Path,
    *,
    max_length: int,
    tokenizer,
) -> None:
    """Pool-build-time guard against MarkerOnlyCollator truncation crashes.

    For each row, apply the chat template AND assert the tokenized length
    leaves room for the trailing ``<|im_end|>`` (i.e. tokenizes to <= max_length).
    A row that truncates the ``<|im_end|>`` post-response slot will trip the
    ``suppress_at_post_response_slot=True`` fail-loud branch in the collator
    a few minutes into training (memory: feedback_cpu_build_time_guard_for_truncation.md).
    """
    n_checked = 0
    n_too_long = 0
    longest = 0
    with open(jsonl_path) as f:
        for line in f:
            if not line.strip():
                continue
            row = json.loads(line)
            messages = list(row["prompt"]) + list(row["completion"])
            ids = tokenizer.apply_chat_template(
                messages, tokenize=True, add_generation_prompt=False
            )
            if isinstance(ids, dict):
                ids = ids["input_ids"]
            n = len(ids)
            longest = max(longest, n)
            if n > max_length:
                n_too_long += 1
            n_checked += 1
    if n_too_long > 0:
        raise RuntimeError(
            f"{n_too_long}/{n_checked} rows in {jsonl_path} exceed max_length={max_length}. "
            f"Longest = {longest} tokens. Increase max_length (and update plan/report) "
            "or drop the offending rows; otherwise MarkerOnlyCollator will crash "
            "minutes into training when it can't find <|im_end|> in the truncated tail."
        )
    logger.info(
        "Pool truncation guard: %d/%d rows fit max_length=%d (longest=%d tokens) at %s",
        n_checked - n_too_long,
        n_checked,
        max_length,
        longest,
        jsonl_path,
    )


def resolve_data_dir(base: Path | None = None) -> Path:
    """Resolve the ``data/issue_520/`` directory; create if missing."""
    if base is None:
        # If EPM_ISSUE520_DATA_DIR is set, use it. Otherwise default to the
        # repo's ``data/issue_520`` (lives alongside ``data/generic_questions``).
        env = os.environ.get("EPM_ISSUE520_DATA_DIR")
        base = Path(env) if env else Path("data/issue_520")
    base.mkdir(parents=True, exist_ok=True)
    return base
