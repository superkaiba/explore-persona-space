"""Held-out target eval prompt panels for issue #503 cross-evaluation.

Per plan §3.4 cross-evaluation rig:

| target | panel | size |
|---|---|---|
| T1 medical | Turner medical eval set (disjoint from training) | 50 × 10 = 500 |
| T2 code | BIG-Code request prompts (disjoint) | 50 × 10 = 500 |
| T3 legal | emergent_plus_legal eval split | 50 × 10 = 500 |
| B1 broad-EM | Betley main-8 | 8 × 100 = 800 |
| B2 broad-syco | fresh 50-wrong-claim panel (#411 schema) | 50 × 10 = 500 |

Panels are stored under ``data/issue503/eval_panels/<panel>.jsonl``,
fetched/generated by ``scripts/issue503_prep_eval_panels.py``. Each
panel file is a JSONL of objects ``{"question": "...", "id": "..."}``.
``load_panel(panel_id)`` returns ``list[str]`` of questions for the
cross-eval rig and is the single API the dispatcher uses.

Disjoint-from-training verification (plan §8 #11): the prep script
spot-checks 5 prompts per panel against each #458 source's training
JSONL using a substring match. The spot-check log is written next to
each panel as ``<panel>.disjoint_audit.json``.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path

logger = logging.getLogger(__name__)

# Plan §3.4 + §3.1 + §3.2 — repo-relative data dir for held-out panels
# Built lazily by scripts/issue503_prep_eval_panels.py.
_DATA_DIR_REL = Path("data") / "issue503" / "eval_panels"


# ── Panel ids and per-target metadata ─────────────────────────────────────

PanelId = str  # one of the keys below

PANEL_SIZES: dict[PanelId, tuple[int, int]] = {
    # (n_prompts, n_rollouts_per_prompt)
    "turner_medical_heldout": (50, 10),
    "bigcode_codereq_heldout": (50, 10),
    "emergent_plus_legal_heldout": (50, 10),
    "betley_main_8": (8, 100),
    "broad_syco_wrong_claims_heldout": (50, 10),
}


def panel_path(panel_id: PanelId, repo_root: Path) -> Path:
    """Return the on-disk path for a panel relative to ``repo_root``."""
    if panel_id not in PANEL_SIZES:
        raise ValueError(f"unknown panel_id={panel_id!r}; known={list(PANEL_SIZES)}")
    return repo_root / _DATA_DIR_REL / f"{panel_id}.jsonl"


def load_panel(panel_id: PanelId, repo_root: Path) -> list[str]:
    """Load the panel's user-prompt strings.

    Each panel file is JSONL with a ``question`` field; we return the
    questions in file order so the per-cell prompt order is reproducible.
    """
    p = panel_path(panel_id, repo_root)
    if not p.exists():
        raise FileNotFoundError(
            f"Panel {panel_id!r} missing at {p}; run "
            f"'uv run python scripts/issue503_prep_eval_panels.py --panel {panel_id}' "
            "to materialize it."
        )
    questions: list[str] = []
    with p.open() as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            obj = json.loads(line)
            q = obj.get("question")
            if not isinstance(q, str):
                raise RuntimeError(
                    f"panel {panel_id!r} line {len(questions) + 1}: missing 'question' string"
                )
            questions.append(q)
    expected_n, _ = PANEL_SIZES[panel_id]
    if len(questions) != expected_n:
        raise RuntimeError(
            f"panel {panel_id!r}: expected {expected_n} questions, found {len(questions)}"
        )
    return questions


def n_verdicts_per_cell(panel_id: PanelId) -> int:
    """Return n_prompts × n_rollouts for the panel — the n of the (k, n) DV."""
    n_prompts, n_rollouts = PANEL_SIZES[panel_id]
    return n_prompts * n_rollouts


def expected_truncation_cap(panel_id: PanelId) -> int:
    """Per plan §8 #12: max_new_tokens cap per target.

    Free-generation evals (alignment, capability) at 512 are fine, but
    marker / end-of-completion evals need 2048 (CLAUDE.md). For the
    judge-rated DVs here (firing rate on free-form completions) the
    threshold is whether the JUDGE sees the relevant span — 512 is
    fine for narrow targets per #411/#458 history; broad-syco short
    claim-agreement responses are 256.
    """
    if panel_id == "broad_syco_wrong_claims_heldout":
        return 256
    if panel_id == "betley_main_8":
        return 512  # Betley main-8 frozen at 512
    # Narrow targets (medical/code/legal): 512 default.
    return 512
